// Что о работе сказано словами. Одна запись — одна работа — одна страница.
//
// Сами записи лежат не здесь, а в `catalogue/`: по файлу на работу, имя файла —
// её `ref`. Раньше это был массив в этом файле; он перестал годиться, когда
// работ стало больше двух десятков и над ними начали работать параллельно.
// Один файл на работу означает, что две одновременные правки разных работ
// не сталкиваются, а добавление работы — это добавление файла, а не правка
// строки посреди чужого списка.
//
// Порядок на указателе задаётся `catalogue/order.json` и только им. Порядок
// файловой системы для этого не годится: он алфавитный, а коллекция — развеска,
// а не лента, и вешают её не по номеру и не по дате.
//
// Здесь нет ничего о том, как работа сделана: ни палитры, ни света, ни
// размеров. Это уехало в соседний репозиторий `wallpaper-gen`, который рисует
// файлы и перечисляет их в `images/manifest/`. Сайт соединяется с ним
// по `ref` и **сам имён файлов не складывает** — иначе два репозитория
// однажды разошлись бы, и страница сослалась бы на несуществующий файл.
//
// **`slug` не меняется после публикации.** Адрес — это всё, что работа
// накопила в поиске; изменённый slug означает новую страницу с нуля.
// Живёт он именно здесь, а не у генератора: адрес страницы — дело сайта,
// имя файла — дело того, кто файл сделал, и совпадение слов в них удобно,
// но не обязательно.
//
// Телефонная и экранная работы — две записи, не одна с двумя кадрами.
// Раньше было иначе, и разобрано это из-за музейных работ: 16:9 и 9:19,5
// не могут оба сохранить половину холста, поэтому у картины кадр ровно один
// и какой именно — свойство картины. Пары остаются видны только глазу.
//
// Тексты по-английски: см. `research/2026-08-16-indexable-collection.md`,
// раздел «Английский». Комментарии остаются на русском — их читаем мы.
//
// `added` — день, когда работа вошла в коллекцию. Отсюда `lastmod` в карте
// сайта: время изменения файла не годится, рендер переписывает его при каждом
// запуске и объявлял бы неизменную работу изменившейся.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const CATALOGUE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), 'catalogue');
export const ORDER_FILE = path.join(CATALOGUE_DIR, 'order.json');

// `ref` попадает в имя файла, поэтому проверяется до того, как из него сложат
// путь: `order.json` правится руками, и строка вида `../../etc/passwd` не должна
// превращаться в чтение чего попало. Проверяет это и `yarn verify`, но здесь
// проверка тоже нужна — файл читается на каждом запросе, а не только перед
// коммитом.
export const REF_PATTERN = /^vl-\d{4}$/;

const readJson = async file => JSON.parse(await fs.readFile(file, 'utf8'));

export const workFile = ref => path.join(CATALOGUE_DIR, `${ref}.json`);

// Каталог читается на каждом запросе, а не при загрузке модуля. Так задумано:
// шага сборки в проекте нет, и публикация работы — это положить файл рядом
// с картинкой, а не передеплоить сайт (AGENTS.md, «Код»). Файлов немного,
// и лежат они в странице кэша операционной системы.
//
// Сломанный каталог роняет запрос, а не показывает половину коллекции.
// Каталог лежит в git и проверяется `yarn verify` перед коммитом — в отличие
// от картинок, которые путешествуют отдельно и потому могут отсутствовать
// законно. Работа без файла просто не показывается; работа без записи — ошибка.
export async function loadWorks() {
  const order = await readJson(ORDER_FILE);
  const bad = order.find(ref => typeof ref !== 'string' || !REF_PATTERN.test(ref));
  if (bad !== undefined) throw new Error(`order.json: недопустимый ref ${JSON.stringify(bad)}`);
  return Promise.all(order.map(ref => readJson(workFile(ref))));
}

// На каких условиях отдаётся работа. Условия — свойство работы, а не сайта:
// плашка нарисована нами, а картина из открытой коллекции музея придёт под
// CC0, и один адрес на обе не годится. Поэтому у записи есть поле `license`,
// а `DEFAULT_LICENSE` — то, что подставляется, пока его не задали.
//
// Присланные посетителями работы не наши, и лицензии у них нет вовсе:
// `gallery.js` не подставляет им ничего.
//
// Public domain и CC0 ведут в один раздел условий и различаются именем: сказать
// «CC0» про гравюру 1705 года было бы неверно — её никто не выпускал под CC0,
// она просто вышла из-под права; а сказать «public domain» про снимок из Getty
// значило бы умолчать, что свободен он по решению держателя, а не по возрасту.
// Возраст сам по себе ничего не решает: гравюра свободна, а снимок гравюры
// бывает новым произведением с живым правообладателем.
export const DEFAULT_LICENSE = 'vellum';
export const LICENSES = {
  vellum: { path: '/license', name: 'Vellum License' },
  'public-domain': { path: '/license#public-domain', name: 'Public domain' },
  cc0: { path: '/license#public-domain', name: 'CC0 1.0' }
};
