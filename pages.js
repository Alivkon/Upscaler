// Карта и robots строятся из того же `SITE_ORIGIN`, поэтому верны в день
// появления домена и безвредны до него.
//
// Сверх списка адресов карта несёт две вещи.
//
// `lastmod` — чтобы обход возвращался к изменившемуся, а не ко всему подряд.
// Стоит он только там, где дата действительно известна: у работы это день,
// когда она вошла в коллекцию, у страницы указателя — самая поздняя дата
// на этой самой странице. У `/restore` и `/license` даты нет, и выдумывать
// её нельзя — Google перестаёт учитывать `lastmod` по всему сайту, если
// однажды застал его неверным.
//
// `<image:image>` — весь канал коллекции это поиск по картинкам, а список
// адресов страниц называет изображения лишь косвенно. Изображения объявлены
// у страницы работы (оба её кадра) и не продублированы у указателя: страница
// работы и есть то место, куда мы хотим привести пришедшего из поиска.
export function sitemap({ items, topics = [], origin }) {
  // Даты сравниваются как строки: и `2026-08-16`, и полный ISO начинаются
  // с года, месяца и дня, поэтому порядок совпадает с хронологическим.
  const latestOf = list =>
    list
      .map(item => item.added)
      .filter(Boolean)
      .sort()
      .at(-1);
  // `images` — файл, который у страницы показан. Google берёт из карты именно
  // файлы, а не выводит их из страницы, так что не названный здесь остаётся
  // ненайденным до тех пор, пока обход не дойдёт до самой страницы.
  const url = (loc, { lastmod, images = [] } = {}) =>
    [
      '  <url>',
      `    <loc>${escape(loc)}</loc>`,
      lastmod ? `    <lastmod>${escape(lastmod)}</lastmod>` : '',
      ...images.map(image => `    <image:image><image:loc>${escape(image)}</image:loc></image:image>`),
      '  </url>'
    ]
      .filter(Boolean)
      .join('\n');

  const entries = [
    // Указатель один, и его `lastmod` — день последнего пополнения коллекции.
    url(`${origin}/`, { lastmod: latestOf(items) }),
    // Файлов у работы четыре — три кадра и целая плита, — и назван каждый:
    // карта перечисляет файлы, а не выводит их из страницы, и не названный
    // здесь остаётся ненайденным, пока обход не дойдёт до самой страницы. Все
    // четыре к тому же стоят на ней настоящими картинками: изображение,
    // объявленное только картой, без страницы вокруг почти не ранжируется.
    //
    // Плюс тот кадр каждой другой версии, который показан в ряду «Other
    // versions» (`versions`). Не плита версии и не все её кадры: карта называет
    // то, что на странице ВИДНО, иначе она обещает обходу файлы, вокруг которых
    // страницы нет. Кадр этот назван здесь тем же выражением, что и там: стояла
    // тут своя копия, `crops.phone`, и в день, когда ряд переехал на `crops.tall`,
    // карта осталась звать обход к файлу, которого больше нет ни на одной
    // странице, — а показанный кадр в ней не назвала.
    ...items.map(item =>
      url(`${origin}/w/${item.slug}`, {
        lastmod: item.added,
        images: [
          ...new Set(
            [
              offered(item),
              tile(item),
              item.crops?.phone,
              item.crops?.wide,
              item,
              ...(item.versions || []).map(version => version.crops?.tall || version)
            ]
              .filter(Boolean)
              .map(file => file.url)
          )
        ].map(address => `${origin}${address}`)
      })
    ),
    // Тематические страницы. `lastmod` у темы — день последнего пополнения
    // самой темы, а не коллекции: тема меняется, когда в неё добавили работу,
    // и объявлять её изменившейся от чужого пополнения значит звать обход зря.
    //
    // Файлы здесь не перечислены. Все они уже названы у страниц работ, а
    // повторять их у темы — обещать обходу, что тот же файл стоит на двух
    // страницах как содержимое; на теме он стоит карточкой, ведущей к работе.
    ...topics.map(topic => url(`${origin}/collection/${topic.slug}`, { lastmod: latestOf(topic.items) })),
    url(`${origin}/restore`),
    url(`${origin}/license`)
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${entries.join('\n')}
</urlset>
`;
}

export const robots = ({ origin }) => `User-agent: *\nAllow: /\n\nSitemap: ${origin}/sitemap.xml\n`;
