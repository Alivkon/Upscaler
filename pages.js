const SITE_NAME = 'Tessarum';
// Сказано про оба вида работ: описание страницы попадает в выдачу,
// а «4k desktop wallpaper» спрашивают отдельно от «phone wallpaper».
const DESCRIPTION =
  'Phone wallpapers at 1440 × 3120 from paintings and engravings in open collections. ' +
  'Free to download, no sign-up. Make your own wallpaper from a picture of your own, up to 4× bigger.';

// Единственное место, где текст становится разметкой. Имена присланных файлов
// попадают на страницу, а они приходят снаружи.
const escape = value =>
  String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');

const specLine = parts =>
  parts
    .filter(Boolean)
    .map((text, index) => `<span${index === 0 ? ' class="lead"' : ''}>${escape(text)}</span>`)
    .join('');

// Ссылка «Реставрировать своё» стоит после скачивания, а не перед ним:
// пришедший из поиска картинок хочет готовую картинку, и закрыть её гейтом
// значит потерять индексацию, то есть весь актив.
//
// «up to 4×» — не довесок, а определение, и оно едет вместе со ссылкой.
//
// Слова «Restore» здесь больше нет, и это отмена прежнего решения, а не
// недосмотр. Стояло так: «Restore — слово музейное, и в этом его ценность:
// коллекция говорит на языке собрания, а не панели управления». Ценность
// настоящая, но тут же рядом было записано и возражение — «в значении
// „увеличить“ его не знает никто», — и оно подтвердилось на живом человеке:
// Чарли прочёл приёмку как приглашение загрузить что-нибудь из нашей же
// коллекции. Комментарий, предсказавший провал, не отменяет провала.
//
// Музейный голос остался там, где слово показано в деле, а не предположено:
// «Restored 5.2× from 750 × 741» на странице работы. Разбор целиком —
// research/2026-08-21-saying-what-the-site-does.md.
//
// Длина по-прежнему на счету: со словами «its size» ссылка занимала 312 px,
// а на экране 320 px под неё остаётся 280 — и она рвалась, оставляя «its
// size» второй строкой. Ссылка `inline-block` с подчёркиванием снизу, так
// что подчёркнута оказалась бы только вторая строка. Нынешние 32 знака
// — примерно 248 px, и в одну строку встают вплоть до 300 px экрана.
const restoreLink = '<a class="link" href="/restore">Make your own wallpaper up to 4×</a>';

// `canonical` необязателен, и это про страницу «не найдено». Канонический адрес
// — заявление «настоящий адрес этой страницы вот такой»; со страницы 404,
// указывающей на указатель, оно читается как «здесь на самом деле указатель»,
// то есть как soft-404: ответ 404 говорит одно, разметка другое. Промолчать
// вернее, чем соврать. Заодно молчит и `og:url` — он про тот же адрес.
//
// `imageWidth`/`imageHeight` идут вместе с `og:image`: без размеров превью
// собирается только после того, как мессенджер сам скачает картинку, а наши
// картинки большие. С размерами карточка рисуется сразу и не съезжает.
// `twitter:card` — там же и по той же причине: без него X показывает не
// превью во всю ширину, а значок величиной с favicon, то есть картинку,
// ради которой ссылкой и делятся, не показывает вовсе.
//
// `noindex` — для снятых с витрины работ. Страница при этом продолжает
// отвечать, и это выбор, а не недоделка: удалить адрес значит потерять всё,
// что он накопил в поиске, а 404 на месте живой страницы копится у Google
// как soft-404. С `noindex` работа выпадает из выдачи чисто, ссылка у того,
// кто её сохранил, продолжает работать, а возвращается работа снятием поля.
function layout({
  title,
  description,
  canonical,
  image,
  imageWidth,
  imageHeight,
  body,
  ld,
  script,
  current,
  noindex = false
}) {
  const nav = [
    ['/', 'Collection', current !== 'restore'],
    ['/restore', 'Make your own', current === 'restore']
  ];
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>${escape(title)}</title>
    <meta name="description" content="${escape(description)}" />
    ${noindex ? '<meta name="robots" content="noindex, follow" />' : ''}
    ${canonical ? `<link rel="canonical" href="${escape(canonical)}" />` : ''}
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="${SITE_NAME}" />
    <meta property="og:title" content="${escape(title)}" />
    <meta property="og:description" content="${escape(description)}" />
    ${canonical ? `<meta property="og:url" content="${escape(canonical)}" />` : ''}
    ${image ? `<meta property="og:image" content="${escape(image)}" />` : ''}
    ${image && imageWidth ? `<meta property="og:image:width" content="${imageWidth}" />` : ''}
    ${image && imageHeight ? `<meta property="og:image:height" content="${imageHeight}" />` : ''}
    ${image ? '<meta name="twitter:card" content="summary_large_image" />' : ''}
    <link rel="icon" type="image/svg+xml" href="/favicon.svg" />
    <link rel="icon" type="image/png" sizes="32x32" href="/favicon-32.png" />
    <link rel="icon" type="image/png" sizes="16x16" href="/favicon-16.png" />
    <link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=Sometype+Mono:wght@400..500&display=swap" rel="stylesheet" />
    <link rel="stylesheet" href="/styles.css" />
    ${ld ? `<script type="application/ld+json">${JSON.stringify(ld, null, 2)}</script>` : ''}
  </head>
  <body>
    <header class="masthead">
      <a class="masthead__mark" href="/">${SITE_NAME}</a>
      <nav class="masthead__nav">
        ${nav.map(([href, label, on]) => `<a href="${href}"${on ? ' aria-current="page"' : ''}>${label}</a>`).join('\n        ')}
      </nav>
    </header>
    <main>${body}</main>
    <div class="lightbox" id="lightbox" hidden>
      <button class="lightbox__close" id="lightbox-close" type="button" aria-label="Close">×</button>
      <img class="lightbox__image" id="lightbox-image" alt="" />
    </div>
    <footer class="colophon">
      <span>${SITE_NAME}</span>
      <a href="/license">License</a>
    </footer>
    ${script ? `<script type="module" src="${script}"></script>` : ''}
  </body>
</html>
`;
}

// Сколько карточек грузится сразу. Ленивая загрузка изображения, видного без
// прокрутки, откладывает LCP ровно той страницы, которую мы хотим ранжировать:
// браузер узнаёт о картинке только после раскладки. Сколько карточек в первом
// ряду — зависит от ширины экрана (сетка `repeat(auto-fill, minmax(200px, 1fr))`),
// поэтому берём безусловно четыре: на широком экране это и есть первый ряд,
// на узком три лишние догрузятся чуть раньше, чем понадобятся.
//
// `fetchpriority="high"` — только первой: приоритет имеет смысл, пока он
// у немногих. Проставленный всем четырём, он ставит их в очередь со стилями
// и шрифтом и замедляет ту самую первую.
const EAGER_CARDS = 4;

// Чем показывается кадр, в отличие от того, чем он отдаётся.
//
// Полный файл остаётся в `src`: им работа объявлена поиску, он же стоит
// в `contentUrl` и в карте сайта, его отдаёт «Download», его открывает
// лайтбокс, и он достаётся браузеру, который `srcset` не понимает.
//
// В самом `srcset` полного файла нет намеренно. Проёмы, в которых работа
// стоит, — ~200 px в карточке указателя и ~290 px на странице работы, —
// не выигрывают от 1440×3120 ни при какой плотности экрана, а стоит он
// 1,06 МБ против 26 КБ у копии. Десять карточек тянули 10,1 МБ картинок
// при 1,8 КБ разметки.
//
// Копий бывает несколько, и тогда браузер выбирает по `sizes` сам. Одна
// ступень обслуживает либо обычный экран, либо плотный, но не оба сразу:
// карточка в 220 px просит 220 px при DPR 1 и 660 px при DPR 3.
const shownWith = (copies, sizes) =>
  copies.length
    ? ` srcset="${copies.map(copy => `${escape(copy.url)} ${copy.width}w`).join(', ')}" sizes="${sizes}"`
    : '';

// Проём страницы работы задан **высотой**, а не шириной: рамка ростом
// `min(72vh, 620px)`, изображение внутри `height: 100%; width: auto`
// (`styles.css`, `.record--plate`). Ширина, которую займёт работа, поэтому
// зависит от её пропорции, и одним числом на всю коллекцию не выражается.
//
// Здесь она и считается. Раньше стояло `290px` — правда ровно до тех пор,
// пока коллекция состояла из телефонных плашек: 1440×3120 при высоте 562 px
// занимает 258 px. Экранная работа 3840×2160 занимает 996 px, и `290px`
// означали, что браузер честно скачивал копию в 480 px и растягивал её
// вчетверо. Отсюда и мыло: работа была не в фокусе, а в три с половиной раза
// меньше проёма, и «резко» становилось только по нажатию — во весь экран
// открывается сам файл, а не копия.
//
// Числа повторяют `styles.css` и обязаны меняться вместе с ним: высота рамки
// минус её поля сверху и снизу. Завышение безопасно — браузер возьмёт ступень
// крупнее и покажет резко; занижение — это и есть мыло.
const PLATE_HEIGHT = 562; // min(72vh, 620px) минус поля рамки
const PHONE_PLATE_HEIGHT = 322; // то же в раскладке одной колонкой, min(46vh, 380px)

const plateSizes = item => {
  const wide = Math.round((PLATE_HEIGHT * item.width) / item.height);
  const narrow = Math.round((PHONE_PLATE_HEIGHT * item.width) / item.height);
  return `(max-width: 860px) ${narrow}px, ${wide}px`;
};

// Чем работа показана и что она отдаёт.
//
// Показывает указатель кадр 9:16, страница работы — 9:19.5, а Download отдаёт
// тот же 9:19.5: коллекция стала телефонной, и то, что видно, обязано быть тем,
// что получат. Плита при этом никуда не делась — она предлагается отдельно,
// ниже, тому, кто хочет кроить сам.
//
// Кадра может не быть: генератор режет их пакетом и до новой работы доходит
// не сразу. Тогда показывается и отдаётся плита. Это не заглушка на время,
// а постоянное правило: работа без кадра должна выглядеть целой работой,
// а не дырой в сетке.
//
// Обе половины совпадают по форме с самой записью — `url`, `filename`,
// `width`, `height`, `bytes`, `copies`, — поэтому подстановка ничего не знает
// о том, кадр перед ней или плита.
const offered = item => item.crops?.phone || item;
const tile = item => item.crops?.tall || item;

// Что написано на карточке. Раньше стояли место и номер — «France · vl-0227», —
// и оба были потрачены впустую. Место называет страну, а ищут не страну:
// набирают «courbet» и «the brook». Номер не говорит ни человеку, ни поиску
// ничего вовсе, а текст ссылки поиск читает и относит к той странице, куда
// ссылка ведёт: сто шестьдесят ссылок «TS·0035» — сто шестьдесят страниц,
// про которые сказано «номер».
//
// Теперь это музейная этикетка: название, под ним автор, ниже размер и номер.
// Название — текст ссылки, потому что это единственное, что стоит относить
// к странице целиком; автор идёт отдельной строкой и попадает на страницу
// как самостоятельные слова.
//
// Хвост заголовка («— landscape phone wallpaper») на карточке отрезан: он
// написан для выдачи и в `<title>` остаётся, а на сетке из ста шестидесяти
// карточек повторялся бы сто шестьдесят раз, говоря каждый раз, что картинка
// на сайте обоев годится в обои.
//
// Работа без имени автора — своя или присланная; имени тогда нет, но строка
// остаётся пустой, а не исчезает. Исчезала — и сетка ломалась: этикетки
// у соседей по ряду становились разной высоты, а из 156 работ автор известен
// у 82, то есть строка пропадала почти у половины карточек, и картинки в ряду
// вставали на разной высоте. Место под имя держит CSS (`.caption__by`),
// поэтому здесь элемент выводится всегда.
// `unknown` пропускается по той же причине, по какой его пропускает байлайн
// страницы работы: «Unknown» — не имя, а шум.
const cardName = item => item.title.split(' — ')[0];

const cardCreator = item => {
  const { creator, creatorKind } = item.provenance || {};
  return creator && creatorKind !== 'unknown' ? creator : '';
};

// Карточка указателя. Ссылок на работу две: изображение и подпись. Подпись
// несёт текст ссылки, а изображение — единственное, на что посетитель целится.
//
// `--ratio` проставлен здесь, а не по загрузке файла: размеры работы известны
// из каталога, и проём принимает её пропорции ещё до того, как что-то
// загрузилось. Иначе указатель прыгал бы по мере загрузки картинок.
function card(item, { eager = false, priority = false } = {}) {
  // Показывается кадр 9:16, отдаётся кадр 9:19.5 — разные файлы, и подпись
  // говорит о том, который отдают: размер под кнопкой «Download» — обещание,
  // а не описание картинки в проёме.
  const shownFile = tile(item);
  const file = offered(item);
  const ratio = `${shownFile.width} / ${shownFile.height}`;
  const loading = ` loading="${eager ? 'eager' : 'lazy'}"${priority ? ' fetchpriority="high"' : ''}`;
  // Сетка — `repeat(auto-fill, minmax(200px, 1fr))`: на телефоне это одна
  // колонка почти во всю ширину, дальше карточка держится около 200–220 px.
  const shown = shownWith(shownFile.copies, '(max-width: 520px) 90vw, 220px');
  const creator = cardCreator(item);
  // Номер встал на место слова «JPEG». Слово это не несло ничего: файлы
  // в коллекции все до одного JPEG, и строка, одинаковая на всех карточках,
  // — это место, занятое ничем. Номер на его месте хотя бы называет работу
  // в собрании, а размер, стоящий первым, остаётся подсвеченным (`.lead`).
  return `<figure class="item">
          <div class="record">
            <a class="record__image" href="/w/${escape(item.slug)}" style="--ratio: ${ratio}" tabindex="-1">
              <img src="${escape(shownFile.url)}"${shown} alt="${escape(item.alt)}" width="${shownFile.width}" height="${shownFile.height}"${loading} />
            </a>
          </div>
          <figcaption class="caption">
            <h3 class="caption__title"><a href="/w/${escape(item.slug)}">${escape(cardName(item))}</a></h3>
            <p class="caption__by">${escape(creator)}</p>
            <p class="caption__spec">${specLine([formatDims(file.width, file.height), item.ref])}</p>
            <a class="link" href="${escape(file.url)}" download>Download</a>
          </figcaption>
        </figure>`;
}

// Пустая рамка среди полных. Приглашение стояло здесь фразой — «Saved a
// picture that's too small for your screen?» — и на странице, где нет ни одного
// предложения, читалось рекламой: пятнадцатый кегль в полную светлоту над
// сеткой из одиннадцати- и двенадцатипиксельных этикеток. Иерархия тут строится
// светлотой (см. шапку файла стилей), и всё, что ярче остального, объявляет себя
// главным на странице.
//
// Карточка ничего не объявляет. Она пользуется тем, из чего сайт и состоит, —
// паспарту, проём, этикетка под ним, — и говорит ровно то же самое, не повышая
// голоса: сто пятнадцать рамок заняты, эта ждёт. Проём при этом тёмный, как
// на приёмке: `.collection .record__image` заливает пустой проём светлым
// `--card`, но это заглушка на время загрузки картинки, и здесь она означала бы
// «карточка не догрузилась», а не «рамка пуста».
//
// Пропорции — 9:16, те же, что у соседей: сетку задаёт `tile(item)`, и рамка,
// вставшая иначе, ломала бы ряд.
//
// Ссылок три, как у настоящей карточки: проём, заголовок и строка внизу. Все
// ведут на приёмку, и подписаны они по-разному не для разнообразия — «Your
// picture» стоит там, где у соседей название работы, а «Make one» там, где
// «Download», то есть каждая читается на своём месте.
//
// Внутри проёма — глагол, и это не стилистика. Стояло «Yours here», и Чарли
// прочёл его как обещание выставить присланное: пустая рамка в ряду занятых
// означает «сюда повесят», и любое существительное внутри неё называет того,
// кого повесят. А публикация чужих работ закрыта — LEGAL.md обещает, что
// закрыта совсем, — то есть надпись обещала ровно то, чего сайт не делает.
// Это та же ошибка, что и `TS·––––` на приёмке, только в другую сторону:
// там гость решил, что загружать надо наше, здесь — что его уйдёт к нам.
//
// «Make your own» называет действие, и слот перестаёт читаться как вакансия.
// Слова те же, что в шапке: карточка и пункт шапки ведут в одно место, и
// одинаковые слова здесь связывают их, а не двоятся.
//
// Проём для чтения с экрана скрыт (`aria-hidden`): те же слова стоят ниже
// в этикетке, и диктор, прочитавший их дважды, объявил бы две работы вместо
// одной.
