// Заголовок в каталоге разрезается на имя работы и хвост для выдачи: «In the
// Waves — seascape phone wallpaper». Режется он по первому тире с пробелами,
// а не по каждому: у тринадцати японских и китайских работ заголовок музейный
// и тире в нём два — «Carp — Aizawa Bunseki — Meiji period, 19th century phone
// wallpaper», — и разрез по всем сразу молча терял хвост, то есть ровно те
// слова, ради которых хвост и пишется.
//
// Тире, оставшиеся внутри имени и хвоста, становятся запятыми. Читают их
// в двух местах — заголовком вкладки и заголовком в выдаче, — и в обоих тире
// работает разделителем уровнем выше запятой: «Gusu Beauty – Winter, snow
// landscape phone wallpaper» распадается надвое там, где часть одна. Запятая
// перечисляет, а заголовок и есть перечисление. Дефис не трогается:
// «Barbed-wire fence» — одно слово, а не два.
const DASH = /\s*[—–]\s*/g;
const titleParts = item => {
  const cut = item.title.indexOf(' — ');
  const [name, kind] = cut < 0 ? [item.title, ''] : [item.title.slice(0, cut), item.title.slice(cut + 3)];
  return { name: name.replace(DASH, ', '), kind: kind.replace(DASH, ', ') };
};

// Что написано на карточке. Раньше стояли место и номер — «France · vl-0227», —
// и оба были потрачены впустую. Место называет страну, а ищут не страну:
// набирают «courbet» и «the brook». Номер не говорит ни человеку, ни поиску
// ничего вовсе, а текст ссылки поиск читает и относит к той странице, куда
// ссылка ведёт: сто шестьдесят ссылок «TS·0035» — сто шестьдесят страниц,
// про которые сказано «номер».
//
// Теперь это музейная этикетка: название, под ним автор, ниже размер и номер.
// Название — текст ссылки, потому что это единственное, что стоит относить
// к странице целиком; автор идёт отдельной строкой и попадает на страницу
// как самостоятельные слова.
//
// Хвост заголовка («— landscape phone wallpaper») на карточке отрезан: он
// написан для выдачи и в `<title>` остаётся, а на сетке из ста шестидесяти
// карточек повторялся бы сто шестьдесят раз, говоря каждый раз, что картинка
// на сайте обоев годится в обои.
//
// Работа без имени автора — своя или присланная; имени тогда нет, но строка
// остаётся пустой, а не исчезает. Исчезала — и сетка ломалась: этикетки
// у соседей по ряду становились разной высоты, а из 156 работ автор известен
// у 82, то есть строка пропадала почти у половины карточек, и картинки в ряду
// вставали на разной высоте. Место под имя держит CSS (`.caption__by`),
// поэтому здесь элемент выводится всегда.
// `unknown` пропускается по той же причине, по какой его пропускает байлайн
// страницы работы: «Unknown» — не имя, а шум.
const cardName = item => titleParts(item).name;

const cardCreator = item => {
  const { creator, creatorKind } = item.provenance || {};
  return creator && creatorKind !== 'unknown' ? creator : '';
};

// Карточка указателя. Ссылок на работу две: изображение и подпись. Подпись
// несёт текст ссылки, а изображение — единственное, на что посетитель целится.
//
// `--ratio` проставлен здесь, а не по загрузке файла: размеры работы известны
// из каталога, и проём принимает её пропорции ещё до того, как что-то
// загрузилось. Иначе указатель прыгал бы по мере загрузки картинок.
function card(item, { eager = false, priority = false } = {}) {
  // Показывается и отдаётся один файл. Раньше это были разные кадры — 9:16
  // в проёме, 9:19.5 по кнопке, — и подпись приходилось оговаривать: размер
  // под «Download» описывал не ту картинку, что видна. Теперь оговаривать
  // нечего, но `tile` и `offered` остаются двумя именами: совпадение
  // сегодняшнее, а вопросы разные — «чем показана» и «что отдаёт».
  const shownFile = tile(item);
  const file = offered(item);
  const ratio = `${shownFile.width} / ${shownFile.height}`;
  const loading = ` loading="${eager ? 'eager' : 'lazy'}"${priority ? ' fetchpriority="high"' : ''}`;
  // Сетка — `repeat(auto-fill, minmax(200rem, 1fr))`: карточка держится около
  // 200–220 базовых пикселей, то есть 350–385 при нынешней крупности.
  //
  // На телефоне стояло `90vw` — след той поры, когда узкая сетка была
  // одноколоночной. Она давно двухколоночная (`minmax(140px, 1fr)`), и проём
  // на экране 390 px замерен: колонка 158.5 px, картинка в ней 145 px, то есть
  // 37vw. `90vw` завышало проём в 2.4 раза, и телефон с DPR 3 тянул ступень
  // 1920 (677 КБ) там, где хватает 480 (43 КБ). 40vw — те же 145 px с небольшим
  // запасом: на экранах 360–430 px проём укладывается в них с обеих сторон,
  // а больший запас перекинул бы DPR 3 на ступень 960 без всякой пользы.
  const shown = shownWith(shownFile.copies, `(max-width: 520px) 40vw, ${scaled(220)}`);
  const creator = cardCreator(item);
  // Номер встал на место слова «JPEG». Слово это не несло ничего: файлы
  // в коллекции все до одного JPEG, и строка, одинаковая на всех карточках,
  // — это место, занятое ничем. Номер на его месте хотя бы называет работу
  // в собрании, а размер, стоящий первым, остаётся подсвеченным (`.lead`).
  return `<figure class="item">
          <div class="record">
            <a class="record__image" href="/w/${escape(item.slug)}" style="--ratio: ${ratio}" tabindex="-1">
              <img src="${escape(shownFile.url)}"${shown} alt="${escape(item.alt)}" width="${shownFile.width}" height="${shownFile.height}"${loading} />
            </a>
          </div>
          <figcaption class="caption">
            <h3 class="caption__title"><a href="/w/${escape(item.slug)}">${escape(cardName(item))}</a></h3>
            <p class="caption__by">${escape(creator)}</p>
            <p class="caption__spec">${specLine([formatDims(file.width, file.height), item.ref])}</p>
            <a class="link" href="${escape(file.url)}" download>Download</a>
          </figcaption>
        </figure>`;
}

// Пустая рамка среди полных. Приглашение стояло здесь фразой — «Saved a
// picture that's too small for your screen?» — и на странице, где нет ни одного
// предложения, читалось рекламой: пятнадцатый кегль в полную светлоту над
// сеткой из одиннадцати- и двенадцатипиксельных этикеток. Иерархия тут строится
// светлотой (см. шапку файла стилей), и всё, что ярче остального, объявляет себя
// главным на странице.
//
// Карточка ничего не объявляет. Она пользуется тем, из чего сайт и состоит, —
// паспарту, проём, этикетка под ним, — и говорит ровно то же самое, не повышая
// голоса: сто пятнадцать рамок заняты, эта ждёт. Проём при этом тёмный, как
// на приёмке: `.collection .record__image` заливает пустой проём светлым
// `--card`, но это заглушка на время загрузки картинки, и здесь она означала бы
// «карточка не догрузилась», а не «рамка пуста».
//
// Пропорции — 9:16, те же, что у соседей: сетку задаёт `tile(item)`, и рамка,
// вставшая иначе, ломала бы ряд.
//
// Ссылок три, как у настоящей карточки: проём, заголовок и строка внизу. Все
// ведут на приёмку, и подписаны они по-разному не для разнообразия — «Your
// picture» стоит там, где у соседей название работы, а «Make one» там, где
// «Download», то есть каждая читается на своём месте.
//
// Внутри проёма — глагол, и это не стилистика. Стояло «Yours here», и Чарли
// прочёл его как обещание выставить присланное: пустая рамка в ряду занятых
// означает «сюда повесят», и любое существительное внутри неё называет того,
// кого повесят. А публикация чужих работ закрыта — LEGAL.md обещает, что
// закрыта совсем, — то есть надпись обещала ровно то, чего сайт не делает.
// Это та же ошибка, что и `TS·––––` на приёмке, только в другую сторону:
// там гость решил, что загружать надо наше, здесь — что его уйдёт к нам.
//
// «Make your own» называет действие, и слот перестаёт читаться как вакансия.
// Слова те же, что в шапке: карточка и пункт шапки ведут в одно место, и
// одинаковые слова здесь связывают их, а не двоятся.
//
// Проём для чтения с экрана скрыт (`aria-hidden`): те же слова стоят ниже
// в этикетке, и диктор, прочитавший их дважды, объявил бы две работы вместо
// одной.
const inviteCard = () => `<figure class="item item--invite">
          <div class="record">
            <a class="record__image" href="/restore" style="--ratio: 9 / 16" tabindex="-1" aria-hidden="true"
              ><span>Make your own</span></a
            >
          </div>
          <figcaption class="caption">
            <h3 class="caption__title"><a href="/restore">Your picture</a></h3>
            <p class="caption__by"></p>
            <a class="link" href="/restore">Start →</a>
          </figcaption>
        </figure>`;

// `eager` — сколько первых карточек грузить сразу. По умолчанию ни одной:
// сетка «ещё из коллекции» на странице работы стоит ниже сгиба, и торопить
// её значит отнимать канал у самой работы.
const grid = (items, eager = 0, lead = '') =>
  `<div class="collection">\n        ${lead ? `${lead}\n        ` : ''}${items
    .map((item, index) => card(item, { eager: index < eager, priority: eager > 0 && index === 0 }))
    .join('\n        ')}\n      </div>`;

// Указатель — вся коллекция одной страницей. Постраничность была и снята:
// она показывала первые десять работ, то есть, пока каталог пополняется
// с конца, всегда одни и те же десять, а остальное пряталось за «Next»,
// куда не ходят. Длина страницы стоит разметки, а не байтов: всё, кроме
// первых карточек, грузится лениво.
// Ряд ссылок на темы под сеткой указателя.
//
// Тема — новый адрес, и прийти на него неоткуда: страницы работ на неё ссылаются
// (`inTopics`), но сами лежат вглубь от указателя. Указатель — самая сильная
// страница сайта, и ссылка отсюда — то немногое в ранжировании, что мы решаем
// сами. Она же и человеку: коллекция в сто работ листается плохо, а «покажи
// только сумрачные» — это то, чего от неё и хотят.
//
// Стоит под сеткой, а не над. Надстрочник над сеткой с указателя убран нарочно
// (см. ниже), и ставить туда ряд ссылок значило бы вернуть его другими словами:
// первым на странице должна стоять работа, а не оглавление.
const topicRow = topics =>
  topics.length
    ? `<nav class="topics" aria-label="Collections">${topics
        .map(topic => `<a href="/collection/${escape(topic.slug)}">${escape(topic.heading)}</a>`)
        .join('\n        ')}</nav>`
    : '';

export function collectionPage({ items, topics = [], origin }) {
  return layout({
    current: 'collection',
    title: `${SITE_NAME}, phone and 4K desktop wallpapers at full resolution`,
    description: DESCRIPTION,
    canonical: `${origin}/`,
    // Превью для мессенджеров и соцсетей: без него ссылка на коллекцию идёт
    // голой строкой. Берём первую работу — она же и первое, что видит
    // открывший, — и берём её телефонным кадром: коллекция телефонная,
    // и превью, показывающее широкую плиту, обещает не то.
    image: items.length ? `${origin}${offered(items[0]).url}` : undefined,
    imageWidth: items.length ? offered(items[0]).width : undefined,
    imageHeight: items.length ? offered(items[0]).height : undefined,
    // Заголовка над сеткой нет. «The collection» стояло 11-м кеглем в верхнем
    // регистре и приглушённым цветом — надстрочник, а не headline: человеку
    // оно ничего не продавало, а поиску не давало ни одного слова, которое
    // кто-нибудь набирает. Слова эти стоят в `<title>` и в описании, и приход
    // идёт не сюда, а из Google Images на страницу работы. Убрав его, мы
    // заодно лишаем Google единственного кандидата на подмену заголовка в
    // выдаче: показывать он будет `<title>`.
    //
    // Плата — разметка страницы начинается с `<h3>` карточек: `<h1>` нет,
    // и Lighthouse на это ругается (`heading-order`). Оставлено сознательно:
    // сетка — сама себе содержание, а прятать заголовок классом ради
    // строчки в аудите значит держать текст, который никто не прочтёт.
    body: `
      ${grid(items, EAGER_CARDS, inviteCard())}
      ${topicRow(topics)}
    `
  });
}

// Ссылка со страницы работы в тему, где эта работа стоит.
//
// Ради обхода в первую очередь. Тема — новый адрес, и прийти на него поиску
// неоткуда: из указателя ссылки нет (там сетка, а не текст), извне тем более.
// Работ же в теме полсотни, и каждая ставит на неё ссылку — это единственное
// в ранжировании, что мы решаем сами.
//
// Текст ссылки несёт слова темы, а не «см. также»: по тексту ссылки страницу
// и понимают, и «here» ведёт ровно никуда. Слова берутся из `term`, а не из
// `heading`: в ряду тем стоит имя раздела целиком («Moody landscape
// collection»), а внутри фразы нужна одна форма определения —
// «more moody landscape phone wallpapers».
const inTopics = topics =>
  topics.length
    ? `<p class="in-topic">${topics
        .map(topic => `<a href="/collection/${escape(topic.slug)}">More ${escape(topic.term)} phone wallpapers →</a>`)
        .join('\n          ')}</p>`
    : '';

// Тематическая страница — часть коллекции, показанная отдельным адресом.
// Устройство и причины — в `collections.js`, там же тексты; здесь только
// разметка, и она нарочно отличается от указателя ровно в одном: над сеткой
// стоит `h1` и абзац.
//
// На указателе заголовка нет намеренно (см. `collectionPage`): там он лишил бы
// нас управления тем, что Google покажет в выдаче. Здесь наоборот — заголовок
// нужен, потому что подменять его есть чем и нечем плохим: `h1` несёт те же
// слова, что `title`, и подмена нам ничего не портит.
//
// Абзац стоит НАД сеткой, а не под ней. Цитируют то, что ассистент прочитал
// первым, и увидеть текст ниже сотни карточек он может, а поставить его первым
// в ответ — нет. Это же и человеку: он листает вниз, а не вверх.
export function topicPage({ topic, items, origin }) {
  return layout({
    current: 'collection',
    title: topic.title,
    description: topic.description,
    canonical: `${origin}/collection/${topic.slug}`,
    // Превью — первая работа темы её телефонным кадром, как и у указателя:
    // тема телефонная, и широкая плита в превью обещала бы не то.
    image: items.length ? `${origin}${offered(items[0]).url}` : undefined,
    imageWidth: items.length ? offered(items[0]).width : undefined,
    imageHeight: items.length ? offered(items[0]).height : undefined,
    // Числа в абзац приходят замером тех же работ, что стоят под ним
    // (`measure` в `collections.js`), а не строкой: вписанное руками число
    // разъезжается со списком молча — и разъехавшееся число в тексте,
    // написанном ради дословной цитаты, врёт уже не нам одним.
    body: `
      <div class="topic">
        <h1 class="topic__title">${escape(topic.heading)}</h1>
        <p class="topic__note">${escape(topic.note(measure(items)))}</p>
      </div>
      ${grid(items, EAGER_CARDS)}
      <p class="topic__back"><a href="/">All ${SITE_NAME} wallpapers →</a></p>
    `
  });
}

// Разметка `ImageObject` даёт Google Images конкретные размеры и подпись,
// а вместе с `license` — значок «Licensable» рядом с результатом. Обязательно
// из двух полей только `license`; `acquireLicensePage` ведёт на саму страницу
// работы, потому что получают файл именно там, а не на странице условий.
//
// Полей нет у присланных работ: лицензии у них нет, а выдумать её нельзя.
const licenseFields = (item, origin) =>
  item.license ? { license: `${origin}${item.license.path}`, acquireLicensePage: `${origin}/w/${item.slug}` } : {};

// Кто работу сделал. У своих — сайт; у гравюры из открытого собрания — тот,
// кто её награвировал, и подставить сюда `Tessarum` значило бы приписать себе
// чужое авторство в машиночитаемом виде, где его прочтут не глядя. Крой
// авторства не создаёт: выбрать кадр и уменьшить — действие механическое.
//
// Кем именно — решает `creatorKind`, а не догадка по строке. Строка `creator`
// человекочитаемая, и одна и та же разметка соврала бы о ней трояко:
//
//   `unknown` — «Unknown (Japan, Edo period)». На странице это правда, а в
//   разметке `Person` по имени Unknown — утверждение, что такой человек был.
//   Поэтому `creator` не подставляется вовсе: из 144 чужих работ имя есть у 72.
//   `organization` — «U.S. Geological Survey». Имя известно, но это не человек,
//   и `Person` здесь — та же ошибка, что `creator: Tessarum` на гравюре Мериан,
//   только тише: неправда о том, кто именно, а не о том, кто вообще.
//   `person` — умолчание, потому что чаще всего автор всё-таки человек.
const CREATOR_TYPE = { person: 'Person', organization: 'Organization' };

const creatorFields = item => {
  // Пустое `provenance` само по себе не значит «сделали мы»: его нет ни у своих
  // работ, ни у присланных. Присланная не наша — об этом же говорит `license`
  // двумя строками выше, — и автор у неё неизвестен: посетитель прислал файл,
  // а не сведения о нём. Поэтому спрашивается источник, а не происхождение:
  // иначе разметка приписывала бы `Tessarum` чужие файлы, причём молча.
  if (!item.provenance) {
    if (item.source !== 'tessarum') return {};
    return { creator: { '@type': 'Organization', name: SITE_NAME }, creditText: SITE_NAME };
  }
  const { creator, credit, date, page, creatorKind } = item.provenance;
  const type = CREATOR_TYPE[creatorKind || 'person'];
  return {
    ...(type ? { creator: { '@type': type, name: creator } } : {}),
    creditText: credit || creator,
    ...(date ? { dateCreated: date } : {}),
    isBasedOn: page
  };
};

// Имя автора в заголовке вкладки, но не на странице: «Gauguin» — то, что
// набирают, и страница, где этого слова нет ни в одной строке, по такому
// запросу не совпадает ни с чем. Из 151 работы открытых собраний имя есть
// у 78, а в заголовке стоит у 10 — остальные 68 отдают запрос даром.
//
// `unknown` пропускается: «In the Waves by Unknown» — не имя, а шум, и таких
// работ 73. Своим работам байлайн тоже не нужен: автор у них один на всю
// коллекцию, и он же стоит в `og:site_name`.
//
// Совпадение проверяется по фамилии, потому что у Одюбона имя уже стоит
// в заголовке работы, и без проверки вышло бы «Wood Pewee by John James
// Audubon — Audubon bird illustration phone wallpaper».
//
// Годы жизни в скобках фамилией не считаются. У одиннадцати работ из японской
// подборки создатель записан так, как его называет музей, — «Yokoyama Taikan
// (1868-1958)», — и последним словом там стоят даты. Заголовок их не содержит
// и содержать не может, так что проверка не срабатывала ни разу и байлайн
// вставал рядом с именем, которое в заголовке уже стояло: «Mount Fuji Rising
// above Clouds by Yokoyama Taikan (1868-1958), Yokoyama Taikan, ca. 1913».
const bylineFor = ({ provenance, title }) => {
  const { creator, creatorKind } = provenance || {};
  if (!creator || creatorKind === 'unknown') return '';
  const surname = creator
    .replace(/\s*\([^()]*\)$/, '')
    .split(' ')
    .at(-1);
  return title.toLowerCase().includes(surname.toLowerCase()) ? '' : ` by ${creator}`;
};

// Одно изображение на страницу, поэтому и разметка одна. Раньше их было две:
// телефонный и экранный кадры делили страницу. Разобрано это из-за музейных
// работ, у которых кадр ровно один по устройству самой картины, — а раз
// у одних одна картинка на страницу, то у всех.
//
// Файл приходит отдельным доводом, а не берётся у записи: страница показывает
// кадр, а не плиту, и размеры в разметке обязаны быть размерами того файла,
// который по кнопке и получат. Заявленные по плите, они разошлись бы с самим
// файлом ровно на величину кадрирования — а сверяет их Google по файлу.
const imageObject = (item, file, origin) => ({
  '@context': 'https://schema.org',
  '@type': 'ImageObject',
  name: item.title,
  description: item.alt,
  contentUrl: `${origin}${file.url}`,
  width: String(file.width),
  height: String(file.height),
  encodingFormat: `image/${formatType(file.url).toLowerCase()}`,
  // Теги пока нигде не образуют страниц: на двенадцати работах вышло бы пять
  // списков по две работы, а тонкие страницы-списки не просто не ранжируются,
  // они вредят. Здесь они всё же читаются — иначе поле было бы мёртвым.
  ...(item.tags.length ? { keywords: item.tags.join(', ') } : {}),
  identifier: item.ref,
  ...creatorFields(item),
  ...licenseFields(item, origin)
});

// Что о чужой работе говорит её страница: кто автор, из какого собрания файл
// и на каких условиях он свободен. Это обещано на странице условий — «каждая
// такая работа называет автора, собрание и адрес, откуда пришла», — а обещание
// стоит ровно столько, сколько стоит его исполнение. Ссылка ведёт на страницу
// первоисточника, чтобы сказанное можно было проверить, не поверив нам на слово.
//
// У своих работ блока нет: автор у них один на всю коллекцию, и повторять его
// на каждой странице — шум.
//
// `work` — как работа называется в собрании — пропускается, когда это то же
// самое, что уже стоит в `<h1>`: «Standing Ksitigarbha» дважды подряд, крупно
// и тут же мелко, читается как сбой вёрстки. Совпадают они у 112 работ
// из 150. У остальных 38 в поле лежит не название, а том и лист — «The Birds
// of America, plate 115», «Kunstformen der Natur, plate 92: Filicinae, Java», —
// и вот это сказать нужно: заголовок называет птицу, а собрание хранит книгу.
function provenance(item, name) {
  if (!item.provenance) return '';
  const { creator, date, work, credit, page } = item.provenance;
  const made = [creator, date].filter(Boolean).join(', ');
  const held = [work === name ? '' : work, credit].filter(Boolean).join(' · ');
  const terms = item.license ? `${escape(item.license.name)} · ` : '';
  return `
            <p class="terms__line">${escape(made)}</p>
            ${held ? `<p class="terms__note">${escape(held)}</p>` : ''}
            <p class="terms__note">${terms}<a href="${escape(page)}">Source file</a></p>`;
}

// Работа «до» и стекло, под которым её сравнивают с тем, что вышло.
//
// СРАВНИВАТЬ ЦЕЛЫЕ КАДРЫ БЕССМЫСЛЕННО, И ЭТО АРИФМЕТИКА, А НЕ ВКУС. Проём
// ростом 603 px (замерено на экране 955 px высотой) показывает работу
// с короткой стороной 3840 примерно в 1/6 натуральной величины, а увеличивали
// её как раз в 3–6 раз (`from` у записей колеблется от 347×752 до 1440×1106).
// Проём, таким образом, ровно отменяет проделанное: «после», ужатое до 603 px,
// несёт столько же подробностей, сколько «до». Две картинки в этом масштабе обязаны совпасть, и кнопка,
// переключавшая их целиком, честно показывала отсутствие разницы, которой
// там и не могло быть. Разница живёт только при 1:1 — значит, на куске кадра.
//
// Стекло разрезано пополам и показывает ОДИН И ТОТ ЖЕ участок сцены из двух
// файлов: слева исходник, растянутый до размера работы, справа сама работа.
// Растягивает исходник браузер, и это не приём ради наглядности — именно это
// происходит с маленькой фотографией, поставленной на экран 4K. Сравнение
// поэтому показывает не лабораторный опыт, а применение.
//
// Сам файл «до» остаётся в разметке изображением: страница сравнивает два
// файла, и второй из них — такая же часть страницы, как первый. Показывает
// его стекло, фоном, поэтому изображение скрыто; но адрес знает сервер, и
// брать его скрипту неоткуда, кроме разметки. Заодно файл успевает загрузиться
// до того, как за него возьмутся.
const beforeFrame = item => `
            <img class="before" id="work-before" src="${escape(item.before)}" alt="" aria-hidden="true" fetchpriority="low" />
            <div class="loupe" id="work-loupe" aria-hidden="true">
              <span class="loupe__pane loupe__pane--after"></span>
              <span class="loupe__pane loupe__pane--before"></span>
            </div>`;

// Файлы, которые страница предлагает кроме того, что стоит в проёме.
//
// Первой — целая работа: её просили назвать прямо, и она здесь не запасной
// вариант, а ответ тому, кого кадр не устроил. Обработку она несёт ту же, что
// и кадр, — приглушение и обесцвечивание идут по плите, а кроят уже
// обработанную, — и видно это по самой плитке: она стоит рядом с кадром, тем
// же светом.
//
// Кадры 9:16 и 16:9 стоят рядом настоящими картинками, а не ссылками словами:
// в поиск по картинкам попадает файл из `src`, и названный только в карте
// сайта, без страницы вокруг, он почти не ранжируется.
//
// Показываются они мелкими копиями, а отдаются целыми: проём здесь 96 px,
// и класть в него файл на несколько мегабайт значило бы платить весом
// страницы за то, чего не видно.
//
// Описания у трёх картинок разные, хотя картина на них одна. Одинаковый `alt`
// трижды на странице — это трижды сказанное одно и то же: экранный диктор
// прочтёт подряд три одинаковых абзаца, а поиск по картинкам не поймёт, чем
// файлы отличаются, кроме адреса. Отличаются же они ровно кадром, и про кадр
// в описании и сказано.
// Одна плитка списка файлов: мелкая копия и подпись, если ей есть что сказать.
// Общая у кадров и у версий, потому что предлагаются они одинаково.
//
// ПОДПИСАН РЯД КАДРОВ, А РЯД ВЕРСИЙ — НЕТ, и размеры в пикселях убраны отовсюду
// (23.08.2026). Кадры отвечают на вопрос «какой формы», а форма на полке в 96 px
// как раз и не читается: 9:16 и 9:19.5 стоят почти одинаковыми полосками, и
// выбирают между ними не глазом, а числом — тем самым, которое человек знает
// про свой экран. «Uncropped» стоит там же и по той же причине: это ответ
// на тот же вопрос, только словом, потому что у целой работы своей пропорции
// нет — она у каждой своя.
//
// Версии отвечают на вопрос «какого света», и на него плитка отвечает сама:
// приглушённая рядом с обычной видна без подписи. Имя обработки при этом
// не пропало, а осталось в `alt` — его читают экранный диктор и поиск
// по картинкам, то есть те, кому смотреть нечем.
//
// ПЛИТКА ОТКРЫВАЕТ ФАЙЛ, А НЕ КЛАДЁТ ЕГО В ЗАГРУЗКИ. Проём — 96 px, и по такой
// копии не видно ни кадра, ни обработки: `download` заставлял решать вслепую и
// платить за ошибку папкой с ненужными файлами. Без атрибута ссылка ведёт туда
// же, куда вела, но браузер показывает картинку целиком — а сохранить её оттуда
// можно в один жест, и уже зная, что сохраняешь. Кнопка Download наверху
// остаётся кнопкой: она отдаёт файл, который посетитель уже видит в проёме.
const fileTile = row => `<li class="alternates__file">
                <a href="${escape(row.file.url)}">
                  <span class="alternates__shot"><img src="${escape(row.file.url)}"${shownWith(row.file.copies, scaled(96))} alt="${escape(row.alt)}" width="${row.file.width}" height="${row.file.height}" loading="lazy" /></span>${
                    row.label ? `\n                  <span class="alternates__label">${escape(row.label)}</span>` : ''
                  }
                </a>
              </li>`;

// Как обработка называется вслух. Внутренние имена — `ceil`, `snap`, `niobe` —
// это имена настроек, по которым их выбирали, и посетителю они не говорят
// ничего: имя должно называть РЕЗУЛЬТАТ, а не файл настроек. Ключи те же, что
// штампует генератор в манифест, — иначе версия выпадет из ряда: имени нет,
// значит, и сказать в `alt`, чем этот файл отличается, нечем.
const BASE_TREATMENT_NAMES = {
  none: 'As scanned',
  bal: 'Colour balanced',
  snap: 'Muted',
  'dim80-desat-whole': 'Muted, stronger',
  ceil: 'Dimmed',
  niobe: 'Dimmed, soft highlights'
};

// У каждой обработки есть двойник с виньеткой — `snap-vig` и так далее, —
// и имя ему даётся тем же способом, каким генератор даёт правило: приставкой
// к исходному. Писать шесть вторых имён руками значило бы обещать, что
// «Muted» и «Muted, darkened corners» разойдутся по смыслу; они не разойдутся,
// углы гаснут поверх той же обработки.
const TREATMENT_NAMES = Object.fromEntries(
  Object.entries(BASE_TREATMENT_NAMES).flatMap(([id, name]) => [
    [id, name],
    [`${id}-vig`, `${name}, darkened corners`]
  ])
);

// Та же картина в других обработках — 22.08.2026, «if several are picked then i
// want all the versions».
//
// ОТДЕЛЬНЫМ РЯДОМ ОТ КАДРОВ, И ЭТО НЕ ОФОРМЛЕНИЕ. Кадр отвечает на вопрос
// «какой формы», версия — «какого света»; сложенные в один ряд, они читались бы
// как один список из шести равноправных файлов, и посетителю пришлось бы
// догадываться, что «16:9» и «Dimmed» — ответы на разные вопросы.
//
// Предлагается телефонный кадр версии, а не её плита: по кнопке Download
// страница отдаёт именно телефонный кадр, и версия обязана давать то же самое,
// иначе «та же картинка, только темнее» окажется неправдой по форме.
const versions = item => {
  const { name } = titleParts(item);
  const rows = (item.versions || [])
    .map(version => {
      const file = version.crops?.tall || version;
      const label = TREATMENT_NAMES[version.treatment];
      return label && { file, alt: `${name}, ${label.toLowerCase()}` };
    })
    .filter(Boolean);
  if (!rows.length) return '';
  return `
          <div class="alternates">
            <h2 class="alternates__heading">Other versions</h2>
            <ul class="alternates__row">
              ${rows.map(fileTile).join('\n              ')}
            </ul>
          </div>`;
};

// Слово «desktop» стоит здесь и больше нигде. В заголовке работы его нет
// намеренно: `offered` отдаёт телефонный кадр, и страница, обещавшая рабочий
// стол, привела бы человека к вертикальной картинке (research/
// 2026-08-21-saying-what-the-site-does.md, «Desktop in the visible copy»).
// А вот эти два файла рабочим столом и являются — 16:9 всегда, плита тогда,
// когда она горизонтальная, — и на них слово сказано правдой.
//
// «background», а не «wallpaper»: alt — это то, что забирает Pinterest в
// описание пина, и в его словаре обои называются так. В `<title>` при этом
// стоит «wallpaper» — слово выдачи. Одно и то же не сказано дважды, но обоих
// слов у работы по одному.
const alternates = item => {
  const { name } = titleParts(item);
  const widePlate = item.width > item.height;
  const rows = [
    {
      file: item,
      label: 'Uncropped',
      alt: `${name}, the whole painting${widePlate ? ', desktop background' : ''}`
    },
    {
      // Узкий кадр. По кнопке отдаётся 9:16, и здесь предлагается то, чего
      // там нет: на экране 19.5:9 и длиннее 9:19.5 садится чуть плотнее.
      // Проиграл он не этим экранам, а всем остальным (treatment.js,
      // PHONE_RATIO), и «чуть плотнее на своём» — ровно то, чем он остался.
      file: item.crops?.phone,
      label: '9:19.5',
      alt: `${name}, cropped to 9:19.5, tall phone background`
    },
    {
      file: item.crops?.wide,
      label: '16:9',
      alt: `${name}, cropped to 16:9, desktop background`
    }
  ].filter(row => row.file);
  // Одна работа без единого кадра — это работа, у которой в проёме и так
  // стоит плита. Предлагать её же второй раз незачем.
  if (rows.length === 1 && !item.crops?.tall) return '';
  return `
          <div class="alternates">
            <ul class="alternates__row">
              ${rows.map(fileTile).join('\n              ')}
            </ul>
          </div>`;
};

// Темы, в которых работа стоит, приходят списком снаружи: страница работы
// о составе тем не знает и знать не должна — состав живёт в `collections.js`,
// и считает его `server.js` один раз на запрос.
export function workPage({ item, others, topics = [], origin }) {
  // Проём показывает кадр 9:16, и всё, что страница о работе утверждает —
  // размер, вес, тип, разметка, превью, — относится к нему же: посетитель
  // получает по кнопке именно этот файл. Плита названа отдельно и ниже.
  const file = offered(item);
  const size = formatDims(file.width, file.height);
  // «4K» стоит в заголовке вкладки и в описании, но не на самой странице.
  // Для поиска `3840` и `4k` — разные строки: работа, у которой сказан только
  // размер, по запросу «4k wallpaper» не совпадает ни с чем, а `4k` — самый
  // частотный модификатор в английском (research/2026-08-16-keyword-research-naming.md,
  // раздел 2). Место выбрано за то, что его не видно: `<title>` живёт во
  // вкладке и в выдаче, на странице его нет, и подпись под работой остаётся
  // такой же чистой, какой была.
  //
  // Условие — обе стороны, а не длинная. 3840×2160 это площадь кадра, и файл,
  // у которого одна сторона доросла, а вторая нет, экран не заполнит: назвать
  // его 4K значило бы пообещать то, чего в нём нет. Подходят 164 работы из 330.
  //
  // Было 69 из 330, и выросло не от новых работ, а от смены кадра: узкий
  // 1772×3840 не дотягивал короткой стороной до 2160, кадр 9:16 — это ровно
  // 2160×3840. Слово стало правдой там, где раньше было бы неправдой.
  // Меряется по длинной и короткой стороне, а не по ширине и высоте: кадр
  // 2160×3840 — это тот же 4K, поставленный стоймя, и телефонная работа
  // теряла бы слово из-за поворота.
  const gauge =
    Math.max(file.width, file.height) >= 3840 && Math.min(file.width, file.height) >= 2160 ? `4K · ${size}` : size;
  // Заголовок работы состоит из имени и хвоста через тире: «In the Waves —
  // seascape phone wallpaper». Имя — то, чем работа называется, хвост — то,
  // чем она является, и написан он для поиска. На странице стоит одно имя:
  // хвост там читался бы как объяснение очевидного — что картинка на сайте
  // обоев годится в обои, — а в `<title>` он остаётся, потому что там его
  // читает не человек, а выдача.
  //
  // Режет заголовок `titleParts`: по первому тире с пробелами, а тире внутри
  // половин становятся запятыми. У работ без хвоста — это тридцать фотографий —
  // имя и есть весь заголовок.
  const { name, kind } = titleParts(item);
  const headline = `${name}${bylineFor(item)}${kind ? `, ${kind}` : ''}`;
  // Заголовком встаёт имя работы — но только если оно у неё есть. Тире
  // отделяет имя от хвоста, написанного для поиска, и у тридцати фотографий
  // тире нет вовсе. Это не пропуск: имени у них и не бывает, есть описание —
  // «Barbed-wire fence in an overgrown field, flat fog light». Описание,
  // поставленное заголовком, читается как подпись, которую забыли сократить,
  // и вдобавок выносит на страницу ровно те слова, которые писались, чтобы
  // их не видели. Номер на его месте честнее и короче.
  //
  // В `<title>` описание при этом остаётся целиком: там его читает выдача.
  const named = Boolean(kind);
  // Строки характеристик под заголовком нет — 23.08.2026. Стояли размер, тип,
  // вес и номер: четыре факта о файле на странице, где файл виден и берётся
  // одной кнопкой. Размер при этом не потерян — он остался в `<title>` и в
  // описании, то есть в выдаче, где выбирают, идти сюда или нет; номер работы
  // остаётся заголовком у тех, у кого нет имени.
  //
  // «Restored from 750 × 741» — утверждение, и проверить его можно только под
  // стеклом. Поэтому подсказка стоит не у кнопки (кнопки и нет: жест живёт на
  // самой работе) и не отдельной строкой, а вплотную к утверждению, которое
  // ею и проверяют. Условие на `before`, а не на `from`: показывает стекло,
  // а размеры — только повод его открыть.
  //
  // Множитель добавлен к утверждению не ради числа, а ради глагола: это
  // единственное место на сайте, где «restore» показано в действии, — и после
  // того, как предложение сделать своё ушло со страницы, единственное, где
  // это слово вообще встречается. Считается он по длинной стороне: пропорцию
  // увеличение сохраняет точно (у всех 51 работы с `from` множители по
  // сторонам совпадают), и одного числа хватает. Знак после запятой один:
  // «5×» вместо 5.18 читалось бы как круглое обещание, которого никто
  // не давал.
  const restored = item.from
    ? `Restored ${Math.round((item.width / item.from[0]) * 10) / 10}× from ${formatDims(...item.from)}`
    : '';
  // Раньше держать и щёлкать считалось одним жестом, и работа со сравнением
  // за это платила: она не открывалась во весь экран вовсе. Стоило это дорого
  // и незаметно — таких работ 51 из 210, на остальных щелчок работал, и разница
  // читалась не как замысел, а как поломка на каждой четвёртой странице.
  //
  // Жесты разводятся не элементом, а временем: короткое нажатие без сдвига —
  // щелчок, всё остальное — «держат». Различает их work.js; сюда приходят
  // роль и доступное имя, потому что до загрузки скрипта проём уже должен
  // объявлять себя тем, чем окажется.
  //
  // Сравнение требует, чтобы в проёме стояла плита. Стекло показывает один
  // и тот же участок сцены из двух файлов, наложенных друг на друга, — а кадр
  // и файл «до» показывают разные куски картины, и совместить их нечем.
  // Поэтому условие не «есть файл до», а «есть файл до и в проёме плита».
  const comparable = Boolean(item.before) && file === item;
  const frame = comparable
    ? 'class="record__image has-work is-comparable" role="button" tabindex="0" ' +
      'aria-label="Click to view full size, hold to compare with the original"'
    : 'class="record__image has-work record__image--zoom"';
  // Проём работы задан высотой (`min(72vh, 620px)`), а ширина берётся из
  // пропорции: у телефонного кадра это около 290 px на большом экране
  // и примерно 70vw на телефоне.
  const shownPlate = shownWith(file.copies, plateSizes(file));
  // Описание пина — своим полем, а не тем же `alt`. `alt` написан для того,
  // кто картинку не видит, и начинается со служебного («Dimmed vertical iPhone
  // background from a painting: …»); в сетке Pinterest от описания видно
  // первые 75–100 знаков — ровно эту часть, а не те слова, по которым ищут.
  // Поле необязательное и откатывается на `alt`, пока не написано: 359 записей
  // пишутся постепенно.
  const pinDescription = item.pin || item.alt;
  // `data-pin-media` — сказанное словами самого Pinterest: сохранять надо
  // полный файл, а не выбранную копию из `srcset`. Атрибуты требуют полного
  // адреса, поэтому здесь `origin`, — но сам `src` остаётся путём от корня,
  // как везде на сайте. `data-pin-description` — то же описание, что и у
  // кнопки: расширением Pinterest сохраняют мимо неё, и без атрибута в пин
  // ушёл бы `alt`.
  //
  // Соседние работы в «More in the collection» этих атрибутов не получают
  // нарочно: пин с них указывал бы на эту страницу, а не на свою.
  const pinned =
    ` data-pin-media="${origin}${escape(file.url)}" data-pin-url="${origin}/w/${escape(item.slug)}"` +
    ` data-pin-description="${escape(pinDescription)}"`;
  // Отправка в Pinterest — контурной кнопкой рядом с Download, а не значком
  // с логотипом. Страница работы набрана музейной этикеткой, и красный кружок
  // в ней читается рекламой; `btn--ghost` — та же форма и тот же шрифт, что
  // у Download, только контуром, и лишнего веса действию не даёт.
  //
  // Адрес — старый `pin/create/button`, тот самый, которым ходит кнопка
  // в браузере. Новый конструктор пинов, куда ссылку вставляют руками,
  // на наши страницы отвечает «no suitable images», а этот открывает выбор
  // доски как ни в чём не бывало (проверено 24.08.2026). Что там сломано,
  // снаружи не видно, и чинить со своей стороны нечего.
  //
  // `media` и `description` проставлены нарочно: без них Pinterest выбирает
  // кадр сам и берёт не тот — на пин уходит целая картина вместо кропа,
  // который страница и предлагает.
  const savePin =
    'https://www.pinterest.com/pin/create/button/' +
    `?url=${encodeURIComponent(`${origin}/w/${item.slug}`)}` +
    `&amp;media=${encodeURIComponent(`${origin}${file.url}`)}` +
    `&amp;description=${encodeURIComponent(pinDescription)}`;
  // Под чертой — только то, что утверждается об этой работе: из чего она
  // сделана, кем и на каких условиях отдаётся. Предложение сделать своё
  // стояло сперва здесь и читалось как ещё одно такое утверждение, потом
  // переехало к Download — а 23.08.2026 ушло со страницы работы вовсе:
  // человек пришёл за картинкой, взял её и не обязан по дороге узнавать,
  // что тут ещё умеют. Приглашение осталось в шапке («Make your own») и
  // на странице прав — там, где его читают нарочно.
  //
  // А блок, которому нечего сказать, не рисуется вовсе: черта без
  // содержания — обещание, что содержание есть.
  const terms = `${
    restored
      ? `<p class="terms__line">${restored}${comparable ? '<span class="terms__hint">Click for full size, hold to compare</span>' : ''}</p>`
      : ''
  }${provenance(item, name)}`;
  return layout({
    current: 'collection',
    // Снятая с витрины работа отвечает как прежде, но выпадает из выдачи.
    // `follow` при этом остаётся: ссылки с неё ведут на работы, которые
    // из коллекции не уходили, и обрывать обход на них незачем.
    noindex: item.hidden,
    title: `${headline}, ${gauge}`,
    description: `${item.alt}. ${gauge}, ${formatType(file.url)}, ${formatBytes(file.bytes)}.${restored ? ` ${restored}.` : ''} Free download, no sign-up.`,
    canonical: `${origin}/w/${item.slug}`,
    image: `${origin}${file.url}`,
    imageWidth: file.width,
    imageHeight: file.height,
    // Разметка описывает тот файл, который страница показывает и отдаёт.
    // Остальные названы на самой странице картинками и в карте сайта —
    // `ImageObject` на страницу один, и делить его между четырьмя файлами
    // значило бы не сказать точно ни об одном.
    ld: imageObject(item, file, origin),
    script: '/work.js',
    body: `
      <div class="plate">
        <figure class="record record--plate">
          <div ${frame} id="work-frame">
            <img id="work-picture" src="${escape(file.url)}"${shownPlate} alt="${escape(item.alt)}" width="${file.width}" height="${file.height}" fetchpriority="high"${pinned} />
            ${comparable ? beforeFrame(item) : ''}
          </div>
        </figure>
        <div class="label">
          <div class="caption">
            <h1 class="caption__title">${escape(named ? name : item.ref)}</h1>
            <div class="actions">
              <a class="btn" href="${escape(file.url)}" download="${escape(file.filename)}">Download</a>
              <a class="btn btn--ghost btn--pin" href="${savePin}" target="_blank" rel="noopener">Pinterest</a>
            </div>
          </div>
          ${terms ? `<div class="terms">${terms}</div>` : ''}
          ${inTopics(topics)}
          ${alternates(item)}
          ${versions(item)}
        </div>
      </div>
      ${others.length ? `<section class="adjacent"><h2 class="heading">More in the collection</h2>${grid(others)}</section>` : ''}
    `
  });
}

