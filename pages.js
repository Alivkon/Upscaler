// Крупность страницы. То же число, что `--scale` в styles.css, и менять его
// нужно вместе с ним: там оно задаёт размер проёма, здесь — какую копию под
// этот проём просить. Разойдутся — картинка станет либо мыльной, либо вчетверо
// тяжелее нужного.
//
// Ниже 860 px масштаба нет (styles.css, медиа-запрос внизу): телефон крупнее
// не становится, и числа для узкой раскладки поэтому остаются базовыми.
const SCALE = 1.75;
const scaled = base => `${Math.round(base * SCALE)}px`;

// Чем показывается кадр, в отличие от того, чем он отдаётся.
//
// Полный файл остаётся в `src`: им работа объявлена поиску, он же стоит
// в `contentUrl` и в карте сайта, его отдаёт «Download», его открывает
// лайтбокс, и он достаётся браузеру, который `srcset` не понимает.
//
// В самом `srcset` полного файла нет намеренно. Проёмы, в которых работа
// стоит, — ~360 px в карточке указателя и ~550 px на странице работы, —
// не выигрывают от 1440×3120 ни при какой плотности экрана, а стоит он
// 1,06 МБ против 26 КБ у копии. Десять карточек тянули 10,1 МБ картинок
// при 1,8 КБ разметки.
//
// Копий бывает несколько, и тогда браузер выбирает по `sizes` сам. Одна
// ступень обслуживает либо обычный экран, либо плотный, но не оба сразу:
// карточка в 220 px просит 220 px при DPR 1 и 660 px при DPR 3.
const shownWith = (copies, sizes) =>
  copies.length
    ? ` srcset="${copies.map(copy => `${escape(copy.url)} ${copy.width}w`).join(', ')}" sizes="${sizes}"`
    : '';

// Проём страницы работы задан **высотой**, а не шириной: рамка ростом
// `min(72vh, 620px)`, изображение внутри `height: 100%; width: auto`
// (`styles.css`, `.record--plate`). Ширина, которую займёт работа, поэтому
// зависит от её пропорции, и одним числом на всю коллекцию не выражается.
//
// Здесь она и считается. Раньше стояло `290px` — правда ровно до тех пор,
// пока коллекция состояла из телефонных плашек: 1440×3120 при высоте 562 px
// занимает 258 px. Экранная работа 3840×2160 занимает 996 px, и `290px`
// означали, что браузер честно скачивал копию в 480 px и растягивал её
// вчетверо. Отсюда и мыло: работа была не в фокусе, а в три с половиной раза
// меньше проёма, и «резко» становилось только по нажатию — во весь экран
// открывается сам файл, а не копия.
//
// Числа повторяют `styles.css` и обязаны меняться вместе с ним: высота рамки
// минус её поля сверху и снизу. Завышение безопасно — браузер возьмёт ступень
// крупнее и покажет резко; занижение — это и есть мыло.
//
// Высота рамки стояла здесь одним числом — 562, то есть потолок 620 минус
// поля, — и это была правда, пока потолок был ниже `72vh` на любом экране.
// С крупностью потолок поднялся до 620 × 1.75, и теперь на обычном мониторе
// рамку задаёт `72vh`, а не он: на экране 1440 px высотой работа занимает
// 950 px, и число 562 означало бы копию вдвое мельче проёма — то самое мыло.
// Поэтому не число, а то же выражение, что в CSS: `sizes` считает `vh` сам,
// проверено в Chrome. Из полей вычтена меньшая граница `clamp` — проём от
// этого объявлен чуть крупнее настоящего, а завышение безопасно.
// Порогов у CSS три (плита складывается в одну колонку на 1160 px, крупность
// пропадает на 860), а здесь их два: окна между 861 и 1160 px получают
// выражение для широкой раскладки и заказывают проём крупнее настоящего.
// Это осознанно: завышение стоит одной ступени лестницы и только на десктопе,
// а третий случай в строке `sizes` стоит того, чтобы его читать при каждой
// правке раскладки.
const PLATE_CAP = 620 * SCALE; // потолок рамки: min(72vh, 620rem)
const PLATE_PAD = 34 * SCALE; // её поля: нижняя граница clamp(34rem, 4.6vw, 58rem)
// В раскладке одной колонкой крупности нет, и потолок `min(46vh, 380px)`
// по-прежнему ниже `46vh` на любом телефоне — здесь хватает числа.
const PHONE_PLATE_HEIGHT = 322;

const plateSizes = item => {
  const ratio = item.width / item.height;
  const wide = `calc((min(72vh, ${PLATE_CAP}px) - ${PLATE_PAD}px) * ${ratio.toFixed(4)})`;
  const narrow = Math.round(PHONE_PLATE_HEIGHT * ratio);
  return `(max-width: 860px) ${narrow}px, ${wide}`;
};

