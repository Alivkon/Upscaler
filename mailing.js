// Куда попадают адреса из рассылки и на каких условиях.
//
// Отдельный файл по тому же шву, что `journal.js` и `limits.js`: у хранения
// адресов своя причина существовать и свои правила, а `server.js` за ориентир
// в 400 строк давно вышел (AGENTS.md).
//
// ЭТО ПЕРВЫЕ ПЕРСОНАЛЬНЫЕ ДАННЫЕ НА САЙТЕ, и оттого всё остальное.
//
// ОТДЕЛЬНЫЙ КАТАЛОГ, А НЕ `log/`. Журнал запросов обещает, что личного в нём
// нет вовсе: ни кук, ни адреса посетителя (journal.js). Дописать туда почтовые
// адреса значило бы отменить это обещание одной строкой — и отменить задним
// числом для всего, что уже записано. Поэтому адреса живут в своём каталоге,
// своим томом и со своими правами; каталог задаётся снаружи (`MAIL_DIR`),
// как и каталог журнала.
//
// ОДИН ФАЙЛ, А НЕ СУТКИ НА ФАЙЛ. Журнал режется по дням, потому что его
// читают за период и старое подметают. Список рассылки читают целиком и
// никогда не подметают: адрес, оставленный год назад, — тот же адрес.
//
// ТАБУЛЯЦИЯ И ТРИ СТОЛБЦА — `time`, `email`, `from`. Разделитель тот же, что
// в журнале, и по той же причине: файл однажды прочтёт глазами человек,
// а второй раз — то, что будет рассылать письма. Ни таба, ни перевода строки
// внутрь значения попасть не может: адрес проходит `isAddress`, а `from`
// сверяется со списком.
//
// `from` — не про человека, а про место: строка под сеткой указателя или
// страница рассылки. Оно говорит, какая из двух форм работает, и стоит того,
// чтобы спросить об этом данные, а не догадку.
import fsp from 'node:fs/promises';
import path from 'node:path';

const FILE = 'subscribers.tsv';
// Шапка пишется при заведении файла. В журнале её нет — там столбцы знает
// сводка, — а этот файл открывает человек, и один раз догадываться, что
// в какой колонке, дороже, чем строка комментария.
const HEADER = '# time\temail\tfrom\n';
// 254 — предел длины адреса в SMTP. Больше не бывает; всё, что длиннее,
// прислано не человеком.
const MAX_LENGTH = 254;
// Строгая проверка адреса здесь не нужна и вредна: единственный настоящий
// способ узнать, что адрес живой, — письмо на него, а оно будет (TODO.md).
// Задача этого выражения другая — не пустить в файл то, что сломает его
// как таблицу или как список: пробелы, табуляции, переводы строк, запятые
// и точки с запятой (разделители адресов у почтовых программ), угловые
// скобки и кавычки. Домен с точкой и буквенной зоной отсекает опечатки
// вроде «name@gmail» — их человек не заметит, а письмо не уйдёт.
const ADDRESS = /^[^\s@,;:<>"'()[\]\\]+@[a-z0-9.-]+\.[a-z]{2,}$/;
const SOURCES = new Set(['collection', 'page']);

// Адрес приводится к нижнему регистру целиком. По букве стандарта левая часть
// чувствительна к регистру, но почтовых систем, которые этим пользуются,
// в природе нет, а пользы от приведения две: `Charlie@…` и `charlie@…` не
// лягут в файл двумя подписчиками, и письмо не уйдёт дважды одному человеку.
export function normalize(value) {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

export function isAddress(value) {
  return value.length <= MAX_LENGTH && !value.includes('..') && ADDRESS.test(value);
}

// Список рассылки: единственное, что он умеет, — принять адрес.
//
// Читать его отсюда нечем и незачем: письма пока не рассылает никто, а когда
// начнёт — читать он будет файл, а не сервер. Держать в сервере способ
// показать список значило бы завести маршрут, который этот список отдаёт.
export function subscribers(directory) {
  const file = path.join(directory, FILE);
  // Уже записанные адреса. Читаются один раз, при первом обращении, и дальше
  // живут в памяти: проверка на повтор иначе перечитывала бы файл на каждое
  // нажатие «Subscribe». Файл при этом остаётся единственной правдой — память
  // наполняется из него и пустеет с перезапуском.
  let known = null;
  // Дозапись идёт в очередь. Два нажатия в одну секунду — это два `appendFile`
  // в один файл, и хуже того, два одинаковых адреса могут разминуться между
  // проверкой на повтор и записью: `await` между ними и есть та щель.
  let queue = Promise.resolve();

  async function read() {
    const seen = new Set();
    let text = '';
    try {
      text = await fsp.readFile(file, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      await fsp.mkdir(directory, { recursive: true });
      await fsp.writeFile(file, HEADER, { flag: 'wx' }).catch(problem => {
        if (problem.code !== 'EEXIST') throw problem;
      });
      return seen;
    }
    for (const line of text.split('\n')) {
      if (!line || line.startsWith('#')) continue;
      const email = line.split('\t')[1];
      if (email) seen.add(email);
    }
    return seen;
  }

  function serial(task) {
    const done = queue.then(task, task);
    // Хвост очереди не должен нести на себе чужую аварию: упавшая запись
    // отвечает своему вызывающему, а следующий в очереди начинает с чистого.
    queue = done.then(
      () => {},
      () => {}
    );
    return done;
  }

  return {
    // Возвращает, что случилось, а не бросает: «не адрес» и «уже есть» —
    // это не аварии, а два из трёх обычных исходов, и отвечать на них
    // посетителю разными словами обязана страница, а не обработчик ошибок.
    async add(value, from) {
      const email = normalize(value);
      if (!isAddress(email)) return 'invalid';
      const source = SOURCES.has(from) ? from : '-';
      return serial(async () => {
        if (!known) known = await read();
        if (known.has(email)) return 'known';
        await fsp.appendFile(file, `${new Date().toISOString()}\t${email}\t${source}\n`);
        known.add(email);
        return 'saved';
      });
    }
  };
}
