// Галочка «Dimmed»: чем страница показывает работу — приглушённым файлом,
// каким её сделала витрина, или сканом, каким её отдал музей.
//
// РАЗМЕТКА С СЕРВЕРА ВСЕГДА ПРИГЛУШЁННАЯ, и это не умолчание, а условие:
// приглушённый файл — тот, которым работа объявлена поиску, а Googlebot
// исполняет скрипты вторым проходом без гарантий по времени. Переключает
// поэтому браузер и переключает уже готовую страницу.
//
// Второй файл приезжает вместе с ней: у каждого элемента, которому есть что
// сменить, стоит `data-scan-<атрибут>` со значением этого атрибута у скана
// (`scanData` в pages.js). Своего списка имён скрипт не держит — он читает
// их с элемента, и новое переключаемое место заводится одной строкой
// в разметке, а не двумя в двух файлах.
//
// Состояние — в `localStorage`: тема и работа это две страницы, и снявший
// галочку в теме должен увидеть в работе то же самое. Ключа нет — приглушено;
// хранилища нет вовсе — страница остаётся приглушённой и работает дальше.
//
// На главной галочки нет и скрипт не подключён: там приглушено всегда.

const KEY = 'dimmed';
const PREFIX = 'data-scan-';

const box = document.querySelector('#dimmed');

// Чтение и запись в try/catch по одной причине: в приватном режиме и при
// запрещённых сайту данных обращение к `localStorage` бросает, а не отвечает
// пустотой. Упасть здесь значит оставить страницу с галочкой, которая
// не работает.
const stored = () => {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
};

const remember = value => {
  try {
    localStorage.setItem(KEY, value);
  } catch {
    // Не запомнили — не беда: на этой странице выбор всё равно применён,
    // а на следующей она откроется приглушённой, как и всякая другая.
  }
};

// Обмен, а не подстановка: прежнее значение остаётся тут же, в парном
// атрибуте, и следующий вызов возвращает всё назад. Второго набора значений
// заводить не нужно, и расходиться нечему.
//
// Пустое значение снимает атрибут, а не пишет пустую строку: `srcset=""`
// браузер понимает не как «копий нет», а как испорченный список.
const exchange = (element, name) => {
  const target = name.slice(PREFIX.length);
  const kept = element.getAttribute(name);
  element.setAttribute(name, element.getAttribute(target) || '');
  if (kept) element.setAttribute(target, kept);
  else element.removeAttribute(target);
};

// Список атрибутов снимается заранее: внутри обмена он меняется.
const swap = () => {
  for (const element of document.querySelectorAll('[data-scan]')) {
    for (const { name } of [...element.attributes]) {
      if (name.startsWith(PREFIX)) exchange(element, name);
    }
  }
};

// Страница пришла приглушённой, поэтому на загрузке работа есть только тогда,
// когда в прошлый раз галочку сняли.
const dimmed = stored() !== '0';
if (!dimmed) swap();

if (box) {
  box.checked = dimmed;
  box.addEventListener('change', () => {
    remember(box.checked ? '1' : '0');
    swap();
  });
}
