// Галочка «Dimmed»: чем страница показывает работу — приглушённым файлом,
// каким её сделала витрина, или сканом, каким её отдал музей.
//
// У работы есть оба файла, и вопрос только в том, какой из них страница
// ПРИВЕЗЛА. Решает это правило работы (`treatment` в wallpaper-gen): почти
// все приезжают приглушёнными, а те, что лучше нетронутыми, — сканом. То, что
// приехало, и есть объявленное поиску: Googlebot исполняет скрипты вторым
// проходом без гарантий по времени, поэтому переключает браузер и переключает
// уже готовую страницу.
//
// Второй файл приезжает вместе с ней: у каждого элемента, которому есть что
// сменить, стоит `data-other-<атрибут>` со значением этого атрибута у второй
// версии (`otherData` в pages.js). Своего списка имён скрипт не держит — он
// читает их с элемента, и новое переключаемое место заводится одной строкой
// в разметке, а не двумя в двух файлах.
//
// `data-shown` говорит, что сейчас в живых атрибутах: `dim` или `scan`.
// Без него не обойтись: работа с правилом `none` привезена сканом, соседняя
// приглушённой, и «поменять всё местами» на второй такой странице вернуло бы
// выбор посетителя обратно.
//
// Состояние — в `localStorage`: работ много, и снявший галочку на одной должен
// увидеть то же на следующей. КЛЮЧА НЕТ — СТРАНИЦА ОСТАЁТСЯ ТАКОЙ, КАКОЙ
// ПРИЕХАЛА, то есть такой, какой её собрал куратор; выбор, сделанный руками,
// сильнее и приводит к одному виду всё. Хранилища нет вовсе — то же самое:
// страница работает дальше.
//
// ГАЛОЧКА ЕСТЬ ТОЛЬКО НА СТРАНИЦЕ РАБОТЫ, и скрипт подключён тоже только там
// (20.09.2026). Сетка — указатель, тема, соседи под работой — показывает то,
// что выбрано по каждой работе: галочка одна, а работ под ней много, и двумя
// положениями смешанную сетку не описать. Спрашивают же о работе, и переключить
// её можно там, где она одна.

const KEY = 'dimmed';
const PREFIX = 'data-other-';

const box = document.querySelector('#dimmed');

// Чтение и запись в try/catch по одной причине: в приватном режиме и при
// запрещённых сайту данных обращение к `localStorage` бросает, а не отвечает
// пустотой. Упасть здесь значит оставить страницу с галочкой, которая
// не работает.
const stored = () => {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
};

const remember = value => {
  try {
    localStorage.setItem(KEY, value);
  } catch {
    // Не запомнили — не беда: на этой странице выбор всё равно применён,
    // а на следующей она откроется такой, какой приехала.
  }
};

// Обмен, а не подстановка: прежнее значение остаётся тут же, в парном
// атрибуте, и следующий вызов возвращает всё назад. Второго набора значений
// заводить не нужно, и расходиться нечему.
//
// Пустое значение снимает атрибут, а не пишет пустую строку: `srcset=""`
// браузер понимает не как «копий нет», а как испорченный список.
const exchange = (element, name) => {
  const target = name.slice(PREFIX.length);
  const kept = element.getAttribute(name);
  element.setAttribute(name, element.getAttribute(target) || '');
  if (kept) element.setAttribute(target, kept);
  else element.removeAttribute(target);
};

// Привести страницу к одному виду. Элемент, уже стоящий в нужном, не трогается
// вовсе — на этом и держится сетка из работ с разными правилами.
//
// Список атрибутов снимается заранее: внутри обмена он меняется.
const show = want => {
  for (const element of document.querySelectorAll('[data-shown]')) {
    if (element.dataset.shown === want) continue;
    for (const { name } of [...element.attributes]) {
      if (name.startsWith(PREFIX)) exchange(element, name);
    }
    element.dataset.shown = want;
  }
};

// Галочка с сервера уже стоит так, как страница собрана. Трогаем и её, и
// страницу только тогда, когда выбор сделан руками.
const choice = stored();
if (choice !== null) show(choice === '0' ? 'scan' : 'dim');

if (box) {
  // ГАЛОЧКА СТАВИТСЯ ВСЕГДА, А НЕ ТОЛЬКО ПО СОХРАНЁННОМУ ВЫБОРУ: при
  // перезагрузке браузер возвращает галочку в то положение, в котором её
  // оставили, поверх приехавшей разметки. Без сохранённого выбора — а это
  // ровно приватное окно и запрещённые сайту данные, ради которых тут
  // try/catch, — страница тогда приезжала бы сканом под нажатой галочкой,
  // и первый клик переключал бы её не в ту сторону. Спрашивается поэтому
  // сама разметка: `data-shown` говорит, чем страница собрана.
  box.checked = choice !== null ? choice !== '0' : document.querySelector('[data-shown]')?.dataset.shown === 'dim';
  box.addEventListener('change', () => {
    remember(box.checked ? '1' : '0');
    show(box.checked ? 'dim' : 'scan');
  });
}
