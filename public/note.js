// Что приёмка сообщает серверу о том, что случилось в браузере.
//
// ЗАЧЕМ. Журнал видит только запросы, а с 24.08 половина работы приёмки
// запросов не делает: отделка без увеличения считается холстом посетителя,
// скачивание берёт blob из памяти. 21 и 23.09 один и тот же посетитель дважды
// увеличил картинку, а потом ещё пять раз приносил файл — и что было дальше,
// журнал сказать не мог: сделал ли он обои у себя, сохранил ли превью правой
// кнопкой или просто ушёл, выглядит одинаково.
//
// КАК. Пустой POST на `/api/note/<что>/<подробности>`. Тела нет. Куку
// `visitor` (limits.js), если она есть, браузер присылает сам, как с любым
// запросом к сайту, но журнал её не пишет: строку пишет тот же `journal.js`,
// что и для любого запроса, — со временем, `visit` и страной. Подробности
// лежат в пути, потому что журнал пишет путь и больше ничего о запросе.
//
// ЧЕГО НЕ ОТПРАВЛЯЕТ. Имени файла — оно бывает личным («passport-john.jpg»),
// а журнал обещает, что личного в нём нет. Самой картинки и её содержимого.
// Только размеры, формат, галочки, способ и секунды. Сервер отвечает 204
// лишь на путь из словаря `NOTED` ниже (`/api/note` в server.js); остальное —
// 404, и в сводку приёмки оно не попадает.
//
// `sendBeacon`, а не `fetch`: он доживает до отправки, даже когда страницу
// закрывают, — а уход со страницы и есть одно из событий. Ответа ждать
// незачем, и отказ ничего не ломает: запись — не часть работы.
export function report(...parts) {
  const path = [
    '/api/note',
    ...parts.map(part =>
      String(part)
        .toLowerCase()
        .replace(/[^a-z0-9.,-]/g, '')
    )
  ];
  try {
    navigator.sendBeacon(path.join('/'));
  } catch {
    // Браузер без `sendBeacon` или с запретом — обои от этого не страдают.
  }
}

// Формат — из короткого списка, а не подтип MIME как есть: подтип присылает
// браузер, и это единственное место записи, где мог бы оказаться произвольный
// текст. HEIC в списке ради того, ради чего пишется отказ: сколько людей
// приносят снимок с айфона.
const FORMATS = ['jpeg', 'png', 'webp', 'avif', 'gif', 'heic', 'heif', 'bmp', 'tiff', 'jxl', 'svg', 'none', 'other'];

export function formatOf(file) {
  const subtype = file.type.split('/').pop().replace(/\+.*/, '') || 'none';
  return FORMATS.includes(subtype) ? subtype : 'other';
}

// Словарь записей — по строке на событие, и в каждой только закрытые списки
// и числа. Читают его обе стороны: сервер решает по нему, какой путь
// записать с кодом 204, и второго списка, который разошёлся бы с этим,
// у него нет.
// Слова сцены — те же, что у `setStage` в intake.js, плюс `offered` и кроме
// `empty`: без принесённого файла ни ухода, ни правой кнопки не пишется.
const HOW = '(pick|drop|paste)';
const FORMAT = `(${FORMATS.join('|')})`;
const SIZE = '\\d{1,5}x\\d{1,5}';
const MAKER = '(server|browser|webgpu|wasm)';
const EFFECT = '(crop|treat|blur|vignette)';
const STAGE = '(measured|offered|working|done)';

export const NOTED = new RegExp(
  '^/api/note/(' +
    [
      `chose/${HOW}/${SIZE}/${FORMAT}/\\d{1,7}kb`,
      `refused/${HOW}/${FORMAT}`,
      `failed/open/${FORMAT}`,
      'failed/(preview|finish|server|browser|show)',
      `made/${MAKER}/(${EFFECT}(,${EFFECT}){0,3}|none)/${SIZE}/\\d{1,5}s`,
      `download/${MAKER}`,
      `rated/${MAKER}/(poor|fair|good)`,
      `(rightclick|left)/${STAGE}`
    ].join('|') +
    ')$'
);
