// Как элемент переводится с одной версии работы на другую — приглушённой на
// скан и обратно. Переключателей два, и у каждого свой охват: галочка
// «Dimmed» на странице работы (`dimmed.js`) переводит всю страницу, значок
// «Try dimmed» на карточке указателя (`try-dimmed.js`) — одну карточку.
// Сам перевод у них один и живёт здесь: заведи его дважды, и однажды
// карточка подменит `src`, а `srcset` оставит.
//
// Второй файл приезжает вместе со страницей: у каждого элемента, которому есть
// что сменить, стоит `data-other-<атрибут>` со значением этого атрибута
// у второй версии (`otherData` в pages.js). Своего списка имён здесь нет —
// они читаются с элемента, и новое переключаемое место заводится одной
// строкой в разметке, а не двумя в двух файлах.
//
// `data-shown` говорит, что сейчас в живых атрибутах: `dim` или `scan`.
// Без него не обойтись: «поменять всё местами», сделанное дважды — по выбору
// из `localStorage` и потом по галочке, — вернуло бы выбор посетителя обратно.

const PREFIX = 'data-other-';

// Обмен, а не подстановка: прежнее значение остаётся тут же, в парном
// атрибуте, и следующий вызов возвращает всё назад. Второго набора значений
// заводить не нужно, и расходиться нечему.
//
// Пустое значение снимает атрибут, а не пишет пустую строку: `srcset=""`
// браузер понимает не как «копий нет», а как испорченный список.
const exchange = (element, name) => {
  const target = name.slice(PREFIX.length);
  const kept = element.getAttribute(name);
  element.setAttribute(name, element.getAttribute(target) || '');
  if (kept) element.setAttribute(target, kept);
  else element.removeAttribute(target);
};

// Элемент, уже стоящий в нужном виде, не трогается вовсе — на этом и держится
// страница из работ с разными правилами.
//
// Список атрибутов снимается заранее: внутри обмена он меняется.
export const turn = (element, want) => {
  if (element.dataset.shown === want) return;
  for (const { name } of [...element.attributes]) {
    if (name.startsWith(PREFIX)) exchange(element, name);
  }
  element.dataset.shown = want;
};
