// Телефонный кадр: пропорция и проём по центру.
//
// Число живёт здесь, а не в каждом модуле по копии: его держат приёмка
// (называет размер до счёта), счёт (режет кадр до модели) и отделка (режет
// его же у готового, когда счёт кадра не знал). Копий было три, и разошлись
// бы они молча — страница пообещала бы один размер, а вышел бы другой.
//
// Проём и порог — одно и то же число, взятое с двух сторон: 2160 × 3840 это
// и кадр под телефон, и условие, по которому витрина зовёт работу обоями
// (`gauge` в pages.js). Пропорция выводится из них, а не ставится рядом
// третьей записью: 2160/3840 и есть 9:16, и разойтись им теперь нечем.
//
// Почему 9:16, а не 9:19.5, — в treatment.js рядом с тем же числом
// (research/2026-08-23-phone-crop-ratio.md).
export const GATE_SHORT = 2160;
export const GATE_LONG = 3840;
export const PHONE_RATIO = GATE_SHORT / GATE_LONG;

// Проём вписывается в картинку целиком и ставится по центру: середина —
// единственное место, о котором можно что-то утверждать, не посмотрев.
export function phoneWindow(width, height) {
  const wide = width / height > PHONE_RATIO;
  const w = wide ? Math.round(height * PHONE_RATIO) : width;
  const h = wide ? height : Math.round(width / PHONE_RATIO);
  return { left: Math.round((width - w) / 2), top: Math.round((height - h) / 2), width: w, height: h };
}
