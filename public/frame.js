// Телефонный кадр: пропорция и проём по центру.
//
// Число живёт здесь, а не в каждом модуле по копии: его держат приёмка
// (называет размер до счёта), счёт (режет кадр до модели) и отделка (режет
// его же у готового, когда счёт кадра не знал). Копий было три, и разошлись
// бы они молча — страница пообещала бы один размер, а вышел бы другой.
//
// Проём и порог — одно и то же число, взятое с двух сторон: 2160 × 3840 это
// и кадр под телефон, и условие, по которому витрина зовёт работу обоями
// (`gauge` в pages.js). Пропорция выводится из них, а не ставится рядом
// третьей записью: 2160/3840 и есть 9:16, и разойтись им теперь нечем.
//
// Почему 9:16, а не 9:19.5, — в treatment.js, над реэкспортом проёма
// (research/2026-08-23-phone-crop-ratio.md).
export const GATE_SHORT = 2160;
export const GATE_LONG = 3840;
export const PHONE_RATIO = GATE_SHORT / GATE_LONG;

// Проём вписывается в картинку целиком и ставится по центру: середина —
// единственное место, о котором можно что-то утверждать, не посмотрев.
export function phoneWindow(width, height) {
  const wide = width / height > PHONE_RATIO;
  const w = wide ? Math.round(height * PHONE_RATIO) : width;
  const h = wide ? height : Math.round(width / PHONE_RATIO);
  return { left: Math.round((width - w) / 2), top: Math.round((height - h) / 2), width: w, height: h };
}

// Один размер на всё, и он не выдуман: это тот самый порог, по которому
// витрина решает, что работа — телефонные обои (`gauge` в pages.js). Выбор из
// четырёх — ×2, ×4, 2K, 4K — стоял на странице, где спросить не у кого: «2K»
// и «4K» ничего не говорят про ЭТУ картинку, а «×4» называет кратность там,
// где человеку нужен размер.
//
// Куда растёт длинная сторона. Условие на витрине двустороннее — длинная от
// 3840 И короткая от 2160, — поэтому считается по обеим. Одной длинной не
// хватило бы: панораму 2:1, растянутую до 3840 по длинной, витрина в обои не
// берёт — короткая выходит 1920. Тогда ведёт короткая, и длинная перерастает
// 3840.
//
// Нижняя граница, а не точный размер: картинку, которая уже крупнее порога,
// уменьшать незачем — от неё просят обои, а не пережатие.
//
// Формула стоит здесь по той же причине, что и числа над ней: копий было две —
// в браузере и на сервере, — и обе называли себя единственной. Разойдись они,
// и страница пообещала бы один размер, а вышел бы другой.
export function targetLongestSideFor(width, height) {
  const long = Math.max(width, height);
  const short = Math.min(width, height);
  // Вверх, а не к ближайшему: короткая сторона, округлённая вниз, выходит
  // 2159 и порог не проходит — то есть промах ровно в том, ради чего считаем.
  return Math.max(long, GATE_LONG, Math.ceil((long * GATE_SHORT) / short));
}

// Дальше этой стороны не растим нигде. В браузере это предел холста: память
// кончается раньше, чем сторона (`MAX_AREA` в upscale-local.js сажает ещё
// ниже). На сервере холста нет, а потолок нужен тот же и по своей причине:
// нижняя граница выше сама себя не ограничивает, и непривычная пропорция
// уводит её куда угодно — панорама 4000 × 1000 просит 8640 по длинной,
// полоса 5000 × 200 просит 54 000. Просьба уходила к Replicate такой, какая
// есть, платим мы за площадь, а обоями сторона в 54 000 не является ни на
// одном экране.
export const MAX_SIDE = 8192;

// Что вернёт сервер с картинки такого размера. Число называет и приёмка, до
// отправки (`serverSize` в intake.js), и считает по нему сам сервер: одно
// правило на обещание и на дело, иначе обещание — просто похожее число.
//
// Третий потолок — ×4, и он появился 24.08 вместе со своей моделью. Replicate
// принимал целый множитель до десяти, и до просьбы дотягивались всегда; своя
// `4x_NMKD-Siax_200k` умеет только ×4, и это не настройка, а её устройство:
// из стороны в 600 пикселей больше 2400 не выйдет, сколько ни проси. Растянуть
// остаток простым увеличением было бы можно, но это уже не работа модели,
// а обещание размера вместо обещания резкости.
export const serverLongestSide = (width, height) =>
  Math.min(targetLongestSideFor(width, height), MAX_SIDE, Math.max(width, height) * 4);

// Во что развернётся кадр при данной длинной стороне — обе стороны, а не одна.
// Копий было две: приёмка называла размер до отправки, сервер уменьшал готовое
// «по длинной стороне, вписав внутрь», и вторая сторона у него выходила из
// пропорции того, что вернула модель, а не из пропорции исходника. На картинке
// 3000 × 2000 это давало 3840 × 2559 там, где страница обещала 3840 × 2560:
// исходник перед счётом ужимался по потолку и на округлении терял сотую долю
// пропорции. Пиксель — мелочь, но обещание от него перестаёт быть обещанием.
export function resultSize(width, height, target) {
  const ratio = target / Math.max(width, height);
  return [Math.round(width * ratio), Math.round(height * ratio)];
}
