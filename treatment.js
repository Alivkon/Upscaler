// Что приёмка делает с чужой картинкой сверх увеличения: обрабатывает
// и кроит под телефон. Обе галочки выключены по умолчанию (`pages.js`),
// и это не осторожность, а определение работы приёмки: она возвращает
// принесённое крупнее, а не переделанным под вкус сайта.
//
// Обработка — `dim`, умолчание витрины с 12.09.2026: работа без поля
// `treatment` выходит именно им, и галочка обязана обещать то, что показывает
// коллекция. `ceil` — то же правило плюс потолок яркости — остался у 11 работ,
// которым он пошёл; вид одиннадцати работ галочка предлагать не может.
//
// Само правило и его числа — в `scripts/research/ceilings.mjs`; оттуда же их
// читает браузер приёмки (`public/treat-local.js`). Числа лежат там, а не
// здесь, потому что считают их двое — сервер и браузер посетителя, — и два
// набора настроек означали бы, что на одну галочку выходят две картинки.
//
// Кадр берётся ДО обработки, а не после. Так дешевле — обработка идёт
// по пикселям, и кадр их отбрасывает раньше, — но главное, что и пестрота,
// и увод, и оба потолка считаются тогда по тому, что увидят. Работа, у которой
// синее небо уходит за край кадра, синей больше не является, и мерить её по
// отрезанному значило бы обесцветить по цвету, которого в файле не осталось.
//
// В коллекции порядок обратный — там кроят уже обработанную плиту, потому что
// плита отдаётся сама по себе и обязана быть обработанной целиком. Здесь
// отдаётся ровно один файл, и мерить его по себе же вернее.
//
// Настройки не просто текущие, а выбранные руками: правило отобрано на двух
// слепых кругах 12.09.2026, где плитки шли без подписей
// (`research/2026-09-12-one-dim-rule.md`). Числа живут в
// `scripts/research/ceilings.mjs` и меняются сразу в обеих половинах; эта
// запись говорит, что менять их — значит менять картинку, которую человек
// выбрал, а не подкрутить параметр.
import sharp from 'sharp';
import { phoneWindow } from './public/frame.js';
import { treat } from './scripts/research/ceilings.mjs';

// Телефонный кадр. 9:16 — не пропорция конкретного телефона, а самая широкая
// из ходовых, и выбрана она именно за это.
//
// Здесь стояло 9:19.5 с обратным доводом: самая узкая заполнит и её, и всё,
// что шире, а «кадр по 9:16 на экране 19.5 не сойдётся». Не сойдётся —
// неправда. Обои телефон масштабирует по заполнению и полей не оставляет
// никогда: кадр 9:16 на экране 19.5 сойдётся, срезав бока. То есть режут
// картинку дважды — мы и телефон, — и вопрос не «останутся ли поля»,
// а «сколько от работы доживёт до экрана».
//
// Считано по 49 выложенным плитам: доля исходной работы, видимая в итоге.
//
//              9:19.5   9:16
//   16:9        44.0%   61.6%
//   18:9        49.5%   54.8%
//   19.5:9      53.6%   50.5%
//   20:9        52.3%   49.3%
//
// Узкий кадр выигрывает 3 очка на длинных экранах и отдаёт 18 на 16:9.
// Причина в том, что на длинном экране наш кадр почти ни при чём: когда
// работа шире и кадра, и экрана — а это 45 плит из 49, — обрезки множатся
// и наша доля сокращается, экран приходит к одному и тому же. Заранее узкий
// кадр не выгадывает там ничего и теряет всё на экранах шире. Разбор:
// research/2026-08-23-phone-crop-ratio.md.
//
// Само число и проём по нему живут в public/frame.js, откуда их берёт и браузер
// приёмки. Здесь была вторая запись того же правила: сервер резал по своей,
// браузер по своей, и совпадали они молча. Проём кормит обещание размера
// (`serverSize` в intake.js) на одном конце и `extract` на другом — то самое
// расхождение, ради которого в frame.js уже свели порог и множитель.
export { phoneWindow };

// Формат сохраняется: приёмка вернула PNG — пусть PNG и останется. Смена
// формата на выходе означала бы, что галочка «потемнее» заодно пережала файл.
const formatOf = format => (format === 'png' ? 'png' : format === 'webp' ? 'webp' : 'jpeg');

// Галочка приходит под именем `treat`, а внутри зовётся `dim`: снаружи это
// «обработать», внутри — единственная обработка, которая есть, правило `dim`.
// Два разных `treat` в одном файле — функция правила и галочка — читались бы
// как одно.
export async function finish(buffer, { treat: dim = false, crop = false } = {}) {
  if (!dim && !crop) return buffer;
  const source = sharp(buffer, { limitInputPixels: false });
  const { width, height, format, hasAlpha } = await source.metadata();
  if (!width || !height) return buffer;
  const out = formatOf(format);
  const window = crop ? phoneWindow(width, height) : null;
  const framed = () => {
    const next = sharp(buffer, { limitInputPixels: false });
    return window ? next.extract(window) : next;
  };
  if (!dim) return framed().toFormat(out).toBuffer();

  const { data, info } = await framed().removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { pixels } = treat(data, info.width, info.height);
  let treated = sharp(pixels, { raw: { width: info.width, height: info.height, channels: 3 } });
  // Прозрачность возвращается на место. Обработка идёт по трём каналам —
  // приглушать нечего там, где пикселя нет, — а `removeAlpha` не прячет
  // прозрачное, а заливает его чёрным: без этого шага логотип на прозрачном
  // фоне вернулся бы на чёрной плашке, и вина легла бы на галочку «потемнее».
  if (hasAlpha) {
    const alpha = await framed().extractChannel('alpha').raw().toBuffer();
    treated = treated.joinChannel(alpha, { raw: { width: info.width, height: info.height, channels: 1 } });
  }
  return treated.toFormat(out).toBuffer();
}
