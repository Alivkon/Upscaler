// Перемешать развеску. Порядок в `catalogue/order.json` складывался
// добавлением сверху (ADDING.md), а работы приезжают партиями: один музей,
// один автор, один вечер отбора вставали в начало целиком. Отсюда и
// «витрина открывается четырьмя букетами ван Хёйсума подряд» — соседство
// в списке повторяло не вкус, а очередь поступления.
//
// Порядок считается хешем от `ref`, а не случайными числами. Причина —
// повторный запуск: со случайными числами каждый запуск даёт новую витрину
// и переписанный целиком diff, а с хешем результат один и тот же, и в diff
// видно ровно то, что изменилось, — приехавшие работы, вставшие вразброс.
// Номер работы при этом на место не влияет: хеш не сохраняет соседства
// соседних номеров, а партия — это и есть соседние номера.
//
// Перетасовать заново — поменять `SALT`. Больше результат ни от чего
// не зависит: те же `ref` и та же соль дают ту же развеску на любой машине.
//
// Скрытые работы (`hidden`) перемешиваются вместе со всеми: они остаются
// в развеске (works.js) и однажды могут вернуться на витрину.
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import { ORDER_FILE } from '../works.js';

const SALT = '2026-08-24';

const key = ref => createHash('sha1').update(`${SALT}:${ref}`).digest('hex');

const order = JSON.parse(await fs.readFile(ORDER_FILE, 'utf8'));
const shuffled = order
  .map(ref => ({ ref, key: key(ref) }))
  .sort((a, b) => (a.key < b.key ? -1 : 1))
  .map(entry => entry.ref);

await fs.writeFile(ORDER_FILE, `${JSON.stringify(shuffled, null, 2)}\n`);
console.log(`развеска перемешана: ${shuffled.length} работ`);
