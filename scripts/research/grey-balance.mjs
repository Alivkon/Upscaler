// Баланс по серому: убрать увод скана, не тронув цвет, который выбрал художник.
//
// Ползунок теплоты (снят 19.08) множил красный канал по всей картине, и снят он
// был потому, что если из оранжевого убрать красный, останется зелёный: у де
// Витте средний тон уходил с 54° на 74° уже при охлаждении на 20 из 60. Дефект
// был не в матрице, а в том, что ползунок смотрел на всю картину сразу, где
// закат и сепия-скан — одно и то же.
//
// Увод и цвет различаются тем, куда они ложатся. Увод скана лежит на КАЖДОМ
// пикселе, включая те, что задуманы бесцветными. Написанный оранжевый лежит на
// оранжевом и оставляет серые серыми. Отсюда мера: смотреть только на пятую
// часть самых бесцветных пикселей и спрашивать, увело ли ИХ.
//
// Коэффициенты нормируются так, что наибольший равен единице. Значит операция
// умеет только убавлять свет и никогда не прибавлять — правило, которое в этом
// проекте не гнётся, — и вся она умещается в одну диагональную матрицу.
//
// Чего мера не может в принципе: у картины, написанной в золотом свете, серые
// ДЕЙСТВИТЕЛЬНО золотые, потому что камень отражает этот свет. «Серые у этой
// работы тёплые» верно и для пожелтевшего лака, и для заката, и по одному файлу
// их не различить. Согласие (agree) говорит, что увод однороден, а не что он
// чужой. Поэтому сила — ползунок, а не вывод: замерено, что на полной силе в
// зелень уходят 12 работ из 599, а на половинной — одна.
//
// Прозаическое изложение и обе кучи ошибок:
// research/2026-08-20-grey-anchor-white-balance.md

const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

// Пятая часть самых бесцветных пикселей — те, что художник задумывал серыми.
const NEUTRAL_SHARE = 0.2;
// Почти чёрное и почти выбитое врут о тоне: у первого не хватает разрядов,
// у второго канал упёрся в потолок и цвет уже не тот, что был.
const LO = 30;
const HI = 225;

const hueOf = (r, g, b) => {
  const mx = Math.max(r, g, b);
  const mn = Math.min(r, g, b);
  const c = mx - mn;
  if (c <= 0) return null;
  const h = mx === r ? ((g - b) / c + 6) % 6 : mx === g ? (b - r) / c + 2 : (r - g) / c + 4;
  return h * 60;
};

/**
 * Замер увода по серым. `data` — сырой RGB без альфы, любой размер.
 * Возвращает null, если бесцветных пикселей набралось меньше 2% работы:
 * это не «увода нет», это «мерить не на чем», и разница важна.
 */
export function greyCast(data) {
  const px = data.length / 3;
  const ch = new Float64Array(px);
  for (let i = 0, n = 0; i < data.length; i += 3, n++)
    ch[n] = Math.max(data[i], data[i + 1], data[i + 2]) - Math.min(data[i], data[i + 1], data[i + 2]);

  // Порог — процентиль ЭТОЙ работы, а не общее число: у пёстрой везде картины
  // всё равно есть своя наименее цветная пятая часть.
  const sorted = Float64Array.from(ch).sort();
  const cut = sorted[Math.floor(sorted.length * NEUTRAL_SHARE)];

  let n = 0;
  let sr = 0;
  let sg = 0;
  let sb = 0;
  let sx = 0;
  let sy = 0;
  let sc = 0;
  for (let i = 0, j = 0; i < data.length; i += 3, j++) {
    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];
    const L = luma(r, g, b);
    if (ch[j] > cut || L < LO || L > HI) continue;
    n++;
    sr += r;
    sg += g;
    sb += b;
    const h = hueOf(r, g, b);
    if (h === null) continue;
    // Тон — угол: усреднять его как число значит развести 359° и 1° по разные
    // стороны круга. Складывается единичными векторами, вес — насыщенность.
    const rad = (h * Math.PI) / 180;
    sx += Math.cos(rad) * ch[j];
    sy += Math.sin(rad) * ch[j];
    sc += ch[j];
  }
  if (n < px * 0.02) return null;

  const mr = sr / n;
  const mg = sg / n;
  const mb = sb / n;
  const target = (mr + mg + mb) / 3;
  const raw = [target / Math.max(1, mr), target / Math.max(1, mg), target / Math.max(1, mb)];
  const top = Math.max(...raw);

  return {
    share: Number((n / px).toFixed(3)),
    grey: [Math.round(mr), Math.round(mg), Math.round(mb)],
    chroma: Math.round(Math.max(mr, mg, mb) - Math.min(mr, mg, mb)),
    hue: sc > 0 ? Math.round(((Math.atan2(sy, sx) * 180) / Math.PI + 360) % 360) : null,
    // Средняя длина результирующего вектора: 1 — все серые уведены в одну
    // сторону, 0 — они гасят друг друга. Это довод, что увод ЕСТЬ, отдельно
    // от того, насколько он велик.
    agree: sc > 0 ? Number((Math.hypot(sx, sy) / sc).toFixed(2)) : 0,
    gain: raw.map(x => Number((x / top).toFixed(3)))
  };
}

/** Коэффициенты на заданной силе: 0 — ничего не делать, 1 — увести серые в ноль. */
export const gainsAt = (gain, strength) => gain.map(x => 1 + (x - 1) * strength);

/** Во сколько раз убавится свет работы. Считать заранее: цена складывается с затемнением. */
export const costOf = gain => Number((1 - luma(gain[0], gain[1], gain[2])).toFixed(3));
