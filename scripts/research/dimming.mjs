// Само приглушение: сила, наклон и мера читаемости подписей.
//
// Вынесено из dim-for-icons.mjs, когда те же числа понадобились на странице
// отбора — смотреть на кандидата приглушённым надо до того, как он попал
// в каталог, а не после. Считать их в двух местах значит развести их
// со временем, поэтому считаются здесь.
//
// Задача не художественная, а измеримая: белая подпись на домашнем экране
// читается, пока фон под ней достаточно тёмный.

// Яркость фона, при которой белая подпись даёт 3.15:1. Порог WCAG для крупного
// текста — 3:1 (яркость 148.9); взято с запасом, потому что среднее по ячейке
// отличается на пару процентов от масштаба измерения, и решённая впритык сила
// на полном разрешении не дотягивала.
export const THRESHOLD = 145;

// Насколько усиливать собственное отклонение работы от серого.
//
// Единица — это простое умножение на канал, без наклона. Оно сохраняет
// отношения каналов и всё равно выглядит серым: цвет опознаётся не только
// тоном, но и положением в диапазоне, и цветность на глаз падает вместе
// с яркостью (эффект Ханта). Кремовая бумага Одюбона при таком приглушении
// читалась как грязная, а не как затенённая.
//
// Постоянного усиления быть не может, и это выяснилось на глаз. При 2.5 на всех
// бумага Одюбона выходила правильно, но «Cluster of road signs against a hazy
// dusk sky» теряла ровно ту дымку, которая стоит в её названии: бледное небо
// становилось звонко-синим. У Гогена кожа уходила в зелень — работе требовалось
// приглушение всего до ×0.93, а наклон она получала полный.
//
// Поэтому усиление привязано к глубине приглушения: возвращать цветность надо
// ровно столько, сколько её потеряно. Работа, приглушённая на три процента,
// не теряет ничего, и трогать её цвет не за что.
export const TILT_PER_STOP = 2.5;

// Предел на канал: без него работа с сильным цветом получила бы наклон,
// который её перекрашивает, а не приглушает.
export const TILT_LIMIT = 0.3;

// Сетка иконок домашнего экрана: четыре в ряд, шесть рядов. Мерить надо не
// всю работу, а те двадцать четыре места, где стоят подписи, — работа бывает
// светлой сверху и тёмной внизу, и среднее по кадру об этом молчит.
const COLS = 4;
const ROWS = 6;

export const clamp = v => (v < 0 ? 0 : v > 255 ? 255 : v);
export const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
export const contrastWithWhite = v => {
  const c = v / 255;
  const l = c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  return 1.05 / (l + 0.05);
};

// Наклон берётся по светлой половине работы: темнеет именно она, и её цвет —
// бумага, небо, шёлк — тот, что должен остаться собой. Считать по всей картинке
// значило бы усреднить бумагу с тушью и получить наклон ни туда ни сюда.
export function tiltFor(data, gain) {
  const lums = [];
  for (let i = 0; i < data.length; i += 3) lums.push(luma(data[i], data[i + 1], data[i + 2]));
  const median = lums.slice().sort((a, b) => a - b)[lums.length >> 1];
  let r = 0;
  let g = 0;
  let b = 0;
  let n = 0;
  for (let i = 0, c = 0; i < data.length; i += 3, c++) {
    if (lums[c] < median) continue;
    r += data[i];
    g += data[i + 1];
    b += data[i + 2];
    n++;
  }
  const mean = [r / n, g / n, b / n];
  const l = luma(...mean);
  if (l < 1) return { tilt: [1, 1, 1], mean, clamped: false };

  // Наклон действует на всю работу сразу — это умножение на канал — и потому
  // тянет к преобладающему тону всё, что в ней есть. Одноцветной работе это
  // ничем не грозит, разноцветной вредит: у Гогена светлая половина — зелёное
  // море, и тот же наклон уводит в зелень кожу фигуры. Отличить одни от других
  // числом не вышло: пробовали цветность среднего против средней цветности
  // пикселей, долю светлой малонасыщенной «бумаги» и ширину светлого пика
  // гистограммы — ни одна мера не разделяет удачные случаи от неудачных.
  // Граница поэтому проводится не здесь, а отбором работ. См. записку
  // research/2026-08-17-dimming-for-icon-legibility.md.
  const raw = mean.map(c => (c / l - 1) * gain);
  const clamped = raw.some(v => Math.abs(v) >= TILT_LIMIT);
  const tilt = raw.map(v => 1 + Math.max(-TILT_LIMIT, Math.min(TILT_LIMIT, v)));
  // Нормируем по яркости: «сила 0.6» должна означать падение яркости в 0.6 раза
  // у любой работы, иначе силы разных работ несравнимы.
  const norm = luma(...tilt);
  return { tilt: tilt.map(v => v / norm), mean, raw, clamped };
}

// Средняя яркость каждой из двадцати четырёх подписей. По ширине берётся
// центральная часть ячейки, по высоте — полоса от 74% до 92% её высоты: там,
// где под иконкой стоит текст, а не сама иконка.
export function cells(data, width, height) {
  const out = [];
  for (let row = 0; row < ROWS; row++)
    for (let col = 0; col < COLS; col++) {
      const cx = ((col + 0.5) * width) / COLS;
      const top = (row * height) / ROWS;
      const cell = height / ROWS;
      const x0 = Math.max(0, Math.round(cx - width / COLS / 2.4));
      const x1 = Math.min(width, Math.round(cx + width / COLS / 2.4));
      let r = 0;
      let g = 0;
      let b = 0;
      let n = 0;
      for (let y = Math.round(top + cell * 0.74); y < Math.round(top + cell * 0.92); y++)
        for (let x = x0; x < x1; x++) {
          const i = (y * width + x) * 3;
          r += data[i];
          g += data[i + 1];
          b += data[i + 2];
          n++;
        }
      out.push(luma(r / n, g / n, b / n));
    }
  return out;
}

export const applied = (data, factors) => {
  const [kr, kg, kb] = factors;
  const out = Buffer.alloc(data.length);
  for (let i = 0; i < data.length; i += 3) {
    out[i] = clamp(data[i] * kr);
    out[i + 1] = clamp(data[i + 1] * kg);
    out[i + 2] = clamp(data[i + 2] * kb);
  }
  return out;
};

// Сила решается, а не подбирается: нужное приглушение — это отношение порога
// к самой светлой подписи. Разница меньше пяти процентов не видна, а работу
// трогает; такие возвращаются как null — их не трогаем.
export function strengthFor(data, width, height) {
  const worst = Math.max(...cells(data, width, height));
  const solved = Math.floor((THRESHOLD / worst) * 100) / 100;
  return { worst, strength: solved >= 0.95 ? null : solved };
}
