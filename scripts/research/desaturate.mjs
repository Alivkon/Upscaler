// Приглушение цвета там, где цветов много, и только там.
//
// Приглушение яркости (dimming.mjs) отвечает за подписи под иконками: белый
// текст читается, пока фон тёмный. Сами иконки — вопрос другой. Иконка
// цветная, и она теряется не на светлом фоне, а на пёстром: если под ней
// лежат красный, синий и жёлтый разом, ей не с чем контрастировать. Работа,
// которая держится одного тона, иконке не мешает — «Offering to the God Pan»
// вся зелёная, и на ней всё видно как есть.
//
// Отсюда правило: обесцвечивать не всё подряд, а по мере пестроты.
//
// Мера пестроты — самая тяжёлая дуга: какая доля всей цветности работы
// умещается в одном секторе тона шириной WINDOW. Считается по гистограмме
// в 360 корзин, взвешенной цветностью; серые пиксели тона не имеют и в счёт
// не идут. Окно едет по кругу, а не стоит на средней: у двухцветной работы
// средний тон попадает ровно в провал между цветами и врёт вдвое.
//
// Способов приглушить два, и они разные по существу:
//
//   whole — обесцветить работу целиком, тем сильнее, чем она пестрее.
//           Буквально то, что просили: одноцветную не трогаем, пёструю
//           уводим в серое.
//
//   apart — оставить цветность главному тону и снять её с остального.
//           Порога не требует вовсе: у одноцветной работы «остального» нет,
//           и она проходит нетронутой сама собой. Пёстрая же не сереет,
//           а сводится к своему цвету — зелёная остаётся зелёной.
//
// Оба сохраняют яркость пикселя буквально: цветность тянется к собственной
// яркости пикселя, а не к серому фиксированному. Приглушение цвета не должно
// шевелить контраст, который уже решён отдельно.
//
// Тождество, на котором держится ползунок силы: при одном множителе на всю
// работу это ровно CSS `filter: saturate(k)` — матрица из спецификации
// filter-effects совпадает с `L + (x−L)k` до округления (проверено на дюжине
// работ при k = 0.75 / 0.35 / 0: худшее расхождение 1 из 255). Поэтому силу
// не нужно рендерить на диск заранее: браузер считает её сам, на любом
// положении ползунка. Пластины на диске нужны только для `apart`, где
// множитель зависит от тона и одной матрицей не выражается.
//
// Отсюда же берётся, что снятая доля цветности равна ровно 1−k: размах
// каналов у `L + (x−L)k` равен k·(размах), и никакой замер не нужен.

export const FLOOR = 12; // ниже этой цветности тона нет, есть шум сжатия
export const WINDOW = 60; // ширина сектора тона, в градусах

// Полоса, на которой «whole» разгоняется от нетронутого до самого серого.
// Взята по пулу отбора: доля 0.90 — это 25-й процентиль сверху, то есть
// две трети работ выше неё и не трогаются вовсе. Ниже 0.55 лежит примерно
// каждая двадцатая — те, у которых цвет действительно спорит с иконкой.
export const HI = 0.9;
export const LO = 0.55;
export const FLATTEST = 0.35;

// «apart»: сектор вокруг главного тона, который сохраняется целиком, и полоса
// плавного спада за ним. Резкая граница даёт кайму на переходах — небо
// в полградуса от предела становится другого цвета, чем соседнее.
export const KEEP = 30;
export const FADE = 60;
export const OUTSIDE = 0.25;

const luma = (r, g, b) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
const clamp = v => (v < 0 ? 0 : v > 255 ? 255 : v);

// Тон в градусах и цветность как размах каналов. HSV, а не что-то честнее:
// мерить надо то же, что видно, а разница между тонами здесь важнее,
// чем их абсолютное положение.
const hueOf = (r, g, b, c, mx) => {
  let h;
  if (mx === r) h = ((g - b) / c + 6) % 6;
  else if (mx === g) h = (b - r) / c + 2;
  else h = (r - g) / c + 4;
  return h * 60;
};

export function hueStats(data) {
  const bins = new Float64Array(360);
  let mass = 0;
  let n = 0;
  for (let i = 0; i < data.length; i += 3) {
    const r = data[i], g = data[i + 1], b = data[i + 2];
    const mx = Math.max(r, g, b);
    const c = mx - Math.min(r, g, b);
    n++;
    if (c < FLOOR) continue;
    bins[Math.round(hueOf(r, g, b, c, mx)) % 360] += c;
    mass += c;
  }
  if (!mass) return { share: 1, hue: null, colour: 0 };
  let sum = 0;
  for (let d = 0; d < WINDOW; d++) sum += bins[d];
  let best = sum;
  let at = 0;
  for (let d = 0; d < 360; d++) {
    sum += bins[(d + WINDOW) % 360] - bins[d];
    if (sum > best) {
      best = sum;
      at = (d + 1) % 360;
    }
  }
  return {
    share: Number((best / mass).toFixed(3)),
    hue: (at + WINDOW / 2) % 360,
    colour: Number((mass / n).toFixed(1))
  };
}

// Пестрота работы в долях: 0 — один тон, трогать не за что; 1 — предельно
// пёстрая. Это ворота, отдельно от силы: сколько снимать, решает вызывающий.
export const polychromy = share => (share >= HI ? 0 : share <= LO ? 1 : (HI - share) / (HI - LO));

// Насколько обесцвечивать работу целиком при силе t. 1 — не трогать.
// t = 1 уводит предельно пёструю работу в серое нацело; STRENGTH — та сила,
// при которой самая пёстрая садится на FLATTEST, то есть прежнее поведение.
export const STRENGTH = Number((1 - FLATTEST).toFixed(3));
export const wholeStrength = (share, t = STRENGTH) => Number((1 - t * polychromy(share)).toFixed(3));

const away = (h, hue) => {
  const d = Math.abs(h - hue) % 360;
  return d > 180 ? 360 - d : d;
};

// Множитель цветности для одного тона при способе «apart».
export const keepAt = (h, hue) => {
  const d = away(h, hue);
  if (d <= KEEP) return 1;
  if (d >= KEEP + FADE) return OUTSIDE;
  const t = (d - KEEP) / FADE;
  return 1 - (1 - OUTSIDE) * (1 - Math.cos(Math.PI * t)) / 2;
};

// Общая часть: тянем пиксель к его собственной яркости с множителем k.
const toward = (data, kOf) => {
  const out = Buffer.allocUnsafe(data.length);
  for (let i = 0; i < data.length; i += 3) {
    const r = data[i], g = data[i + 1], b = data[i + 2];
    const mx = Math.max(r, g, b);
    const c = mx - Math.min(r, g, b);
    const k = c < FLOOR ? 1 : kOf(hueOf(r, g, b, c, mx));
    if (k === 1) {
      out[i] = r;
      out[i + 1] = g;
      out[i + 2] = b;
      continue;
    }
    const l = luma(r, g, b);
    out[i] = clamp(Math.round(l + (r - l) * k));
    out[i + 1] = clamp(Math.round(l + (g - l) * k));
    out[i + 2] = clamp(Math.round(l + (b - l) * k));
  }
  return out;
};

// Сила передаётся, а не берётся из STRENGTH: на снимке настроек стоит 55%,
// а STRENGTH — это 65%. По умолчанию сила прежняя, поэтому вызовы без неё
// работают как раньше.
export function desaturate(data, mode, stats, t = STRENGTH) {
  const s = stats ?? hueStats(data);
  if (mode === 'whole') {
    const k = wholeStrength(s.share, t);
    return { pixels: k === 1 ? Buffer.from(data) : toward(data, () => k), k, stats: s };
  }
  if (s.hue === null) return { pixels: Buffer.from(data), k: 1, stats: s };
  return { pixels: toward(data, h => keepAt(h, s.hue)), k: null, stats: s };
}
